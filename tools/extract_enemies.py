#!/usr/bin/env python3
"""Extract room spawn flags and fixed enemy records from original Z80 6154.
Usage: extract_enemies.py ROM [--write]. Unported types are retained, not substituted.
"""
import argparse,json
from pathlib import Path
from probe import load_rom
from castle_room_objects import make_machine,call
from extract_room_links import COUNTS
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('rom',type=Path);p.add_argument('--write',action='store_true');a=p.parse_args();data=load_rom(a.rom)
flags=[];fixed=[];report=[]
for stage in range(12):
    ptr=int.from_bytes(data[0x1c5a6+stage*2:0x1c5a8+stage*2],'little');off=0x1c000+ptr-0x8000
    fs=list(data[off:off+COUNTS[stage]]);flags.append(fs+[0]*(9-len(fs)))
    m=make_machine(data);m.memory[0xd000]=stage;m.memory[0xd002]=data[0x1e6a+stage];call(m,0x6154)
    rows=[]
    for room in range(9):
        records=[]
        if stage and room<COUNTS[stage]:
            base=0xdb00+(stage-1-3*data[0x1e6a+stage])*256+room*16
            for slot in range(4):
                b=list(m.memory[base+4*slot:base+4*slot+4])
                records.append([b[0],(b[1]&15)*16,b[1]&240,b[3]])
        else:records=[[0,0,0,0] for _ in range(4)]
        rows.append(records)
        if stage and room<COUNTS[stage]:report.append(dict(stage=stage,room=room,flags=fs[room],unsupported_channels=fs[room]&0x74,fixed=[dict(raw_type=b[0],type=b[0]&127,x=b[1],y=b[2],id=b[3],integrated=(b[0]&127)==5) for b in records if b[0]]))
    fixed.append(rows)
s='/* Generated by extract_enemies.py from the supplied MSX2 ROM. */\n#ifndef VK_ENEMY_ROOMS_H\n#define VK_ENEMY_ROOMS_H\n#include "../enemies.h"\n'
s+='static const EnemyU8 vk_enemy_room_count[12] = {'+','.join(map(str,COUNTS))+'};\n'
s+='static const EnemyU8 vk_enemy_room_flags[12][9] = {\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in flags)+'};\n'
s+='typedef struct { EnemyU8 raw_type,x,y,id; } VKFixedEnemy;\nstatic const VKFixedEnemy vk_fixed_enemies[12][9][4] = {\n'
for rows in fixed:s+=' {\n'+''.join('  {'+','.join('{'+','.join(map(str,b))+'}' for b in row)+'},\n' for row in rows)+' },\n'
s+='};\n#endif\n'
path=ROOT/'sgdk/src/generated/enemy_rooms.h'
if a.write:path.write_text(s);(ROOT/'research/stages-1-10/MSX2_ENEMIES.json').write_text(json.dumps(report,indent=2)+'\n')
else:assert path.read_text()==s
print('73 rooms: enemy flags and fixed lists extracted/verified; fixed records:',sum(len(r['fixed']) for r in report))
