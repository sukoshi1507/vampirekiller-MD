#!/usr/bin/env python3
"""Room change freeze table of the port, from the openMSX measure of every arrival room.

build_room_freeze.py merge EPISODES.jsonl...   merges the outputs of tools/run_room_freeze_trace.py
                                               into research/room-freeze-rooms.json
build_room_freeze.py [--check]                 writes (or checks) sgdk/src/generated/room_freeze_table.h
A room keeps its most frequent value (the lower median of its samples on a tie).
"""
import json,statistics,sys
from collections import Counter,defaultdict
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TRACE=ROOT/'research/room-freeze-rooms.json'
HEADER=ROOT/'sgdk/src/generated/room_freeze_table.h'
COUNTS=[3,8,6,6,6,6,6,9,8,9,9,6,12,12,8,10,10,12,10]   # decode_room_links.py, stage 0 = courtyard

def pick(values):
    top=Counter(values).most_common();best=[v for v,n in top if n==top[0][1]]
    return best[0] if len(best)==1 else statistics.median_low(values)

def merge(paths):
    samples=defaultdict(list)
    for path in paths:
        for line in Path(path).read_text().splitlines():
            r=json.loads(line)
            if r['dark'] is not None:samples[(r['stage'],r['room'])].append([r['frames'],r['dark']])
    rooms=[]
    for stage,count in enumerate(COUNTS):
        for room in range(count):
            s=samples[(stage,room)];assert len(s)>=3,(stage,room,s)
            rooms.append(dict(stage=stage,room=room,frames=pick([a for a,_ in s]),dark=pick([b for _,b in s]),samples=s))
    assert set(samples)<={(r['stage'],r['room']) for r in rooms}
    TRACE.write_text(json.dumps(dict(
        method='openMSX C-BIOS_MSX2, tools/run_room_freeze_trace.py: frames = VBLANK samples with C000 = 9, '
               'dark = samples from the first one to 47D4 (display off); room forced by C5B4 and C41B = FF (B98C)',
        rooms=rooms),indent=1)+'\n')

def header():
    rooms=json.loads(TRACE.read_text())['rooms']
    table={(r['stage'],r['room']):(r['frames'],r['dark']) for r in rooms}
    assert sorted(table)==[(s,r) for s,c in enumerate(COUNTS) for r in range(c)]
    text='/* Generated by tools/build_room_freeze.py from research/room-freeze-rooms.json (openMSX). */\n'
    text+='#ifndef VK_ROOM_FREEZE_TABLE_H\n#define VK_ROOM_FREEZE_TABLE_H\n'
    text+='#define VK_FREEZE_STAGES 19\n#define VK_FREEZE_ROOMS 12\n'
    text+='/* {frames, dark} of each arrival room; {0, 0}: no such room. */\n'
    text+='static const VKRoomFreezeTiming vk_room_freeze_table[VK_FREEZE_STAGES][VK_FREEZE_ROOMS] = {\n'
    for stage,count in enumerate(COUNTS):
        text+='    { '+', '.join('{%d, %d}'%table[(stage,room)] for room in range(count))+' },   /* stage %d */\n'%stage
    return text+'};\n#endif\n'

if __name__=='__main__':
    if sys.argv[1:2]==['merge']:merge(sys.argv[2:])
    elif '--check' in sys.argv:assert HEADER.read_text()==header(),'room_freeze_table.h is stale'
    else:HEADER.write_text(header())
