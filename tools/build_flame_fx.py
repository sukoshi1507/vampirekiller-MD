#!/usr/bin/env python3
"""Build original *prototype* flame and spark animation for SGDK (not MSX assets).
Tiles are SGDK 4bpp, ordered top-left, top-right, bottom-left, bottom-right.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MAIN = (ROOT/'research/flame_v15_source.txt').read_text()
raw = re.search(r'static const u32 flame_tiles\[64\] = \{(.*?)\};', MAIN, re.S)
if not raw:
    raise SystemExit('Original V15 flame pixels not found; run from the unmodified V15 source')
words = [int(x,16) for x in re.findall(r'0x([0-9a-fA-F]+)UL',raw.group(1))]
assert len(words)==64

def decode(t):
    image=[[0]*16 for _ in range(16)]
    for ty in range(2):
        for tx in range(2):
            tile=t[(ty*2+tx)*8:(ty*2+tx+1)*8]
            for r,w in enumerate(tile):
                for c in range(8): image[ty*8+r][tx*8+c]=(w>>(4*(7-c)))&15
    return image

def encode(image):
    result=[]
    for ty in range(2):
        for tx in range(2):
            for r in range(8):
                w=0
                for c in range(8): w=(w<<4)|(image[ty*8+r][tx*8+c]&15)
                result.append(w)
    return result

original=[decode(words[i*32:(i+1)*32]) for i in range(2)]
frames=[]
for phase in range(4):
    src=original[phase%2]
    frame=[[0]*16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            shift = (1 if phase == 1 else (-1 if phase==3 else 0)) if y<9 else 0
            xx=x+shift
            if not 0<=xx<16: continue
            old=src[y][x]
            if not old: continue
            # Three heated-color bands in addition to the original 14/15 ink.
            val=2 if old==15 and y>5 else (3 if old==15 else 1)
            if (x+y+phase)%7==0 and val==1: val=14
            frame[y][xx]=val
    frames.append(frame)

sparks=[]
for phase in range(3):
    im=[[0]*16 for _ in range(16)]
    points=[(8,3),(2,6),(13,5),(5,12),(11,12),(8,8)]
    for idx,(x,y) in enumerate(points):
        x+=(-phase if idx%2 else phase)
        y+=(phase if idx%3 else -phase)
        if 1<=x<15 and 1<=y<15:
            im[y][x]=15 if phase==0 else 2
            if phase<2:
                im[y-1][x]=14
                im[y][x-1]=3
    sparks.append(im)

flat=[v for frame in frames+sparks for v in encode(frame)]
assert len(flat)==7*4*8
out=ROOT/'sgdk/src/generated/flame_fx_md.h'
out.parent.mkdir(parents=True,exist_ok=True)
lines=['/* Generated by tools/build_flame_fx.py from V15 prototype pixels. NOT ROM-extracted. */',
       '#ifndef VK_FLAME_FX_MD_H', '#define VK_FLAME_FX_MD_H',
       '#define VK_FLAME_FRAMES 4', '#define VK_SPARK_FRAMES 3',
       '#define VK_FLAME_TILES_PER_FRAME 4',
       'static const u32 vk_flame_fx_tiles[224] = {']
for i in range(0,len(flat),8):
    lines.append('    '+', '.join(f'0x{w:08X}UL' for w in flat[i:i+8])+(',' if i+8<len(flat) else ''))
lines+=['};','#endif']
out.write_text('\n'.join(lines)+'\n')
print('generated',out,'frames',len(frames),'sparks',len(sparks))
