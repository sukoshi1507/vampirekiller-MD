#!/usr/bin/env python3
"""The old man of the walls (wall_view.c, five frames of 32 x 24) in the 16-bit art (research/gfx16.md).

usage: build_wall16.py [--preview FILE.png]

Writes sgdk/src/generated/wall16_md.c/.h: vk_wall16_tiles, an array of the SAME layout as vk_wall_frame_tiles
(object_tiles_md.c: 5 frames of 12 tiles, 4 x 3 sprite tiles), drawn with PAL1 (vk_item16_palette, the palette of
the 16-bit objects) in 16-bit mode, like the keys and candles.

The MSX frames share one picture (hood, face, hands, staff, black outline) and differ by the colour of the robe
(salmon, red, black while it blinks, white, blue: the result of the hit). The shape is the MSX one; the picture
is the redrawn one: outline in black, robe in three tones (light from the upper left: light rim on top and left, dark
on the right and below, fold lines in the dark tone), staff and hands in the skin / wood tones of the objects.
Roles are read from frame 3 (white robe); the robe tones of each frame are entries of PAL1.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'sgdk/src/generated'
K = 2                                   # black entry of PAL1
# (light, middle, dark) of the robe of each frame: entries of vk_item16_palette
ROBE = {0: (1, 7, 5),                   # salmon (MSX colour 3)
        1: (8, 8, 4),                   # red (8)
        2: (6, K, K),                   # black while it blinks (2)
        3: (14, 10, 3),                 # white (14)
        4: (13, 12, 3)}                 # blue (15)
SKIN, WOOD = 1, 7
W, H = 32, 24


def frames():
    src = (GEN / 'object_tiles_md.c').read_text()
    m = re.search(r'vk_wall_frame_tiles\[\d+\] = \{(.*?)\};', src, re.S)
    words = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]
    out = []
    for f in range(5):
        t = words[f * 96:(f + 1) * 96]
        out.append([[(t[(x // 8 * 3 + y // 8) * 8 + y % 8] >> (28 - 4 * (x % 8))) & 15 for x in range(W)]
                    for y in range(H)])
    return out


def draw(frame):
    base = frames()[3]                  # roles: 0xE robe, 2 outline / fold, 1 skin, 3 wood / shade
    robe = [[base[y][x] == 14 for x in range(W)] for y in range(H)]

    def at(m, x, y):
        return 0 <= x < W and 0 <= y < H and m[y][x]
    solid = [[base[y][x] != 0 for x in range(W)] for y in range(H)]
    edge = [[any(not at(solid, x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)) for x in range(W)]
            for y in range(H)]
    # the body: the robe and its fold lines (dark pixels inside the picture below the head), whose rim is lit
    body = [[robe[y][x] or (base[y][x] == 2 and y >= 12 and not edge[y][x]) for x in range(W)] for y in range(H)]
    hi, mid, lo = ROBE[frame]
    img = [[0] * W for _ in range(H)]
    for y in range(H):
        xs = [x for x in range(W) if robe[y][x]]
        for x in range(W):
            c = base[y][x]
            if not c:
                continue
            if body[y][x] and not robe[y][x]:
                p = lo
            elif robe[y][x]:
                if not at(body, x, y - 1) or not at(body, x - 1, y):
                    p = hi
                elif not at(body, x, y + 1) or not at(body, x + 1, y) or (xs and xs[-1] - x < 2):
                    p = lo
                else:
                    p = mid
            elif c == 2:
                p = K
            elif c == 1:
                p = SKIN
            else:
                p = WOOD
            img[y][x] = p
    return img


def words(img):
    out = []
    for cx in range(4):                 # sprite tiles column by column, 3 per column
        for cy in range(3):
            for r in range(8):
                v = 0
                for c in range(8):
                    v = (v << 4) | img[cy * 8 + r][cx * 8 + c]
                out.append(v)
    return out


def preview(path, imgs):
    from PIL import Image
    pal = re.findall(r'0x[0-9A-Fa-f]+', (GEN / 'items16_md.c').read_text().split('vk_item16_palette')[1].split('}')[0])
    rgb = [(0, 0, 0)] + [(((int(p, 16) >> 1) & 7) * 36, ((int(p, 16) >> 5) & 7) * 36, ((int(p, 16) >> 9) & 7) * 36)
                         for p in pal[1:16]]
    im = Image.new('RGB', (5 * 36, 28), (60, 90, 60))
    for f, img in enumerate(imgs):
        for y in range(H):
            for x in range(W):
                if img[y][x]:
                    im.putpixel((f * 36 + 2 + x, 2 + y), rgb[img[y][x]])
    im.resize((im.width * 8, im.height * 8), Image.NEAREST).save(path)


def main():
    imgs = [draw(f) for f in range(5)]
    w = [v for img in imgs for v in words(img)]
    (GEN / 'wall16_md.h').write_text("""/* Generated by tools/build_wall16.py. */
#ifndef VK_WALL16_MD_H
#define VK_WALL16_MD_H
#include <genesis.h>
/* The five frames of the old man (vk_wall_frame_tiles layout), drawn with PAL1 (vk_item16_palette). */
extern const u32 vk_wall16_tiles[480];
#endif
""")
    (GEN / 'wall16_md.c').write_text('/* Generated by tools/build_wall16.py. */\n#include "wall16_md.h"\n\n'
                                      'const u32 vk_wall16_tiles[480] = {\n' +
                                      ''.join('    ' + ','.join(f'0x{v:08X}' for v in w[i:i + 8]) + ',\n'
                                              for i in range(0, len(w), 8)) + '};\n')
    if len(sys.argv) > 2 and sys.argv[1] == '--preview':
        preview(sys.argv[2], imgs)
    return 0


if __name__ == '__main__':
    sys.exit(main())
