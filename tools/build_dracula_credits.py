#!/usr/bin/env python3
"""Execute66BA/6743 and compile the initial credits image and41 written text bands."""
import argparse
from probe import ROOT
from dracula_graphics import room,tiles

def generate():
 h=room();m=h.cpu;mem=m.memory;h.call(0x47B1);mem[0xCE40]=1;h.call(0x66BA)
 words=[];lookup={}
 def record(x,y,w,height):
  raw=tiles(h,x,y,w,height);mapping=[]
  for i in range(0,len(raw),8):
   t=tuple(raw[i:i+8])
   if t not in lookup:lookup[t]=len(words)//8;words.extend(t)
   mapping.append(lookup[t])
  return mapping
 base=record(0,0,256,256);bands=[];ys=[]
 for p in range(6000):
  mem[0xC003]=(p+1)&255;old=mem[0xCE31];h.call(0x66BA)
  if mem[0xCE31]!=old:
   y=(mem[0xCE33]+216)&255;assert y%8==0
   ys.append(y);bands.append(record(0,y,256,8))
  if mem[0xCE32]:break
 assert len(bands)==41 and len(ys)==41
 header=f'''/* Generated by tools/build_dracula_credits.py through66BA/6743. */
#ifndef VK_DRACULA_CREDITS_H
#define VK_DRACULA_CREDITS_H
#include <genesis.h>
#define VK_DRACULA_CREDIT_TILES {len(words)//8}
extern const u32 vk_dracula_credit_tiles[{len(words)}];
extern const u16 vk_dracula_credit_base[1024];
extern const u16 vk_dracula_credit_band[41][32];
extern const u8 vk_dracula_credit_y[41];
#endif
'''
 data='/* Generated by tools/build_dracula_credits.py. */\n#include "dracula_credits.h"\n'
 def array(name,kind,v,width):return f'const {kind} {name}={{\n'+''.join(' '+','.join((f'0x{a:08X}' if kind=='u32' else str(a)) for a in v[i:i+width])+',\n' for i in range(0,len(v),width))+'};\n'
 data+=array(f'vk_dracula_credit_tiles[{len(words)}]','u32',words,8)
 data+=array('vk_dracula_credit_base[1024]','u16',base,32)
 data+=array('vk_dracula_credit_y[41]','u8',ys,16)
 data+='const u16 vk_dracula_credit_band[41][32]={\n'+''.join(' {'+','.join(map(str,b))+'},\n' for b in bands)+'};\n'
 return {'dracula_credits.h':header,'dracula_credits.c':data},{'words':words,'base':base,'bands':bands,'y':ys}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out,meta=generate()
 for name,s in out.items():
  dest=ROOT/'sgdk/src/generated'/name
  if a.check:assert dest.read_text()==s,name
  else:dest.write_text(s)
 print('Dracula credits renderer:41 bands,',len(meta['words'])//8,'tiles','CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
