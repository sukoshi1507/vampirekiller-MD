#!/usr/bin/env python3
"""Extract stage-12 static tilemaps, raw B9D3 room links and BBCD secret passages.

No Z80 execution: the backgrounds are decoded using the existing ROM-based
extract_rooms decoder, but collision behavior is NOT validated against 4F83.
Usage: python tools/build_stage12_foundations.py /path/to/reference.rom
The reference ROM is SHA256-checked by probe.load_rom and is never copied.
"""
import hashlib
import json
import sys
from pathlib import Path
from probe import load_rom
from extract_rooms import decode_room
from decode_room_links import decode, check, cpu_to_file

ROOT = Path(__file__).resolve().parents[1]
STAGE = 12
COUNT = 12

def extract(data):
    graph = decode(data)[STAGE]
    assert len(graph['rooms']) == COUNT
    # The original table deliberately includes a one-way link 5 -> 6.
    # Preserve it; do not impose symmetry on the ROM.
    assert check([graph]) == ['s12 r5 RIGHT->6 but r6 LEFT->None']
    maps, rooms = [], []
    for r in range(COUNT):
        meta, graphics, cells = decode_room(data, STAGE, r)
        assert meta['status'] == 'static_background_decoded' and len(cells) == 768
        maps.append(cells)
        rooms.append({'room': r, 'map_cpu': meta['map_cpu'],
                      'map_sha256': hashlib.sha256(bytes(cells)).hexdigest(),
                      'graphics_sha256': hashlib.sha256(graphics).hexdigest()})
    # BB9A reads BBCD in bank 13, terminated with FF. Every four-byte record:
    # stage, (destination << 4) | source_room, Y, X. See research/enemy-behavior.md.
    off = cpu_to_file(0xBBCD)
    passages=[]
    while data[off] != 0xFF:
        stage, packed, y, x = data[off:off+4]
        assert stage == STAGE
        src, dest = packed & 15, packed >> 4
        assert src < COUNT and dest < COUNT
        passages.append({'source':src, 'destination':dest, 'x':x, 'y':y,
                         'rom_offset':f'0x{off:05X}'})
        off += 4
        assert len(passages) <= COUNT
    assert len(passages) == 10
    # Spawn-channel flag bytes are read from the ROM's bank-14 pointer table;
    # these are NOT the fixed-enemy records generated by executing 6154.
    flag_pointer_offset = 0x1C5A6 + STAGE * 2
    flag_ptr = int.from_bytes(data[flag_pointer_offset:flag_pointer_offset+2], 'little')
    assert 0x8000 <= flag_ptr < 0xA000
    flag_offset = 0x1C000 + flag_ptr - 0x8000
    assert flag_offset + COUNT <= len(data)
    flags = list(data[flag_offset:flag_offset+COUNT])
    # D002 is the ROM stage grouping byte; do not interpret as an enemy count.
    stage_group = data[0x1E6A + STAGE]
    return graph, maps, rooms, passages, flags, flag_ptr, flag_offset, stage_group

def generate(data):
    graph, maps, rooms, passages, flags, flag_ptr, flag_offset, stage_group = extract(data)
    out = ROOT / 'sgdk/src/generated'
    c = ['/* Stage 12 static room tilemaps and links decoded directly from the reference ROM.',
         ' * These are NOT 4F83 execution-verified collision maps and are NOT wired to gameplay.',
         ' * tools/build_stage12_foundations.py; no Z80 emulator required. */',
         '#include "stage12_foundations.h"',
         'const VKByte vk_stage12_tiles[VK_STAGE12_ROOM_COUNT][768] = {']
    for cells in maps:
        c += ['    {'] + ['        '+','.join(map(str,cells[i:i+32]))+',' for i in range(0,768,32)] + ['    },']
    c += ['};', 'const VKRoomLink vk_stage12_raw_links[VK_STAGE12_ROOM_COUNT] = {']
    for r in graph['rooms']:
        c.append('    {'+','.join('VK_ROOM_NONE' if r[d] is None else str(r[d]) for d in ('UP','DOWN','LEFT','RIGHT'))+',0},')
    c += ['};', 'const VKStage12Passage vk_stage12_raw_passages[VK_STAGE12_PASSAGE_COUNT] = {']
    c += [f'    {{{p["source"]}, {p["destination"]}, {p["x"]}, {p["y"]}}},' for p in passages]
    c += ['};', 'const VKByte vk_stage12_raw_spawn_flags[VK_STAGE12_ROOM_COUNT] = {'+','.join(map(str,flags))+'};', '']
    c += ['/* Deterministic lookup of ROM BBCD entries; no gameplay activation. */',
          'const VKStage12Passage *vk_stage12_find_raw_passage(VKByte source, VKByte x, VKByte y)',
          '{',
          '    unsigned int i;',
          '    for (i = 0; i < VK_STAGE12_PASSAGE_COUNT; ++i) {',
          '        const VKStage12Passage *p = &vk_stage12_raw_passages[i];',
          '        if (p->source == source && p->x == x && p->y == y) return p;',
          '    }',
          '    return 0;',
          '}', '']
    (out/'stage12_foundations.c').write_text('\n'.join(c))
    (out/'stage12_foundations.h').write_text('''/* Raw ROM data staging; not an enabled gameplay stage. */
#ifndef VK_STAGE12_FOUNDATIONS_H
#define VK_STAGE12_FOUNDATIONS_H
#include "../room_manager.h"
#define VK_STAGE12_ROOM_COUNT 12
#define VK_STAGE12_PASSAGE_COUNT 10
typedef struct { VKByte source, destination, x, y; } VKStage12Passage;
extern const VKByte vk_stage12_tiles[VK_STAGE12_ROOM_COUNT][768];
extern const VKRoomLink vk_stage12_raw_links[VK_STAGE12_ROOM_COUNT];
extern const VKStage12Passage vk_stage12_raw_passages[VK_STAGE12_PASSAGE_COUNT];
extern const VKByte vk_stage12_raw_spawn_flags[VK_STAGE12_ROOM_COUNT];
/* Raw ROM table lookup only. Does not execute the MSX2 secret-passage state machine. */
const VKStage12Passage *vk_stage12_find_raw_passage(VKByte source, VKByte x, VKByte y);
#endif
''')
    report={'rom_sha256':hashlib.sha256(data).hexdigest(), 'stage':STAGE,
            'type':'raw ROM extracted data; NOT an executable stage',
            'room_count':COUNT, 'link_table_cpu':f'0x{graph["pointer"]:04X}',
            'links':graph['rooms'], 'rooms':rooms, 'secret_passages':passages,
            'spawn_flags_rom':{'pointer_table_offset':'0x1C5BE',
              'pointer_cpu':f'0x{flag_ptr:04X}', 'file_offset':f'0x{flag_offset:05X}',
              'room_flags':flags, 'note':'raw channel flags, not fixed enemies'},
            'stage_group_d002':{'file_offset':'0x1E76','value':stage_group},
            'entry_openmsx_trace':{'x':16,'y':176,'facing':'right',
             'source':'research/stage11-level.md (KD trace)'},
            'unverified':['4F83 collision execution','5A49/5B1B objects and candles',
              '6154 enemies','stage12 boss','secret passage state machine','SGDK runtime']}
    (ROOT/'research/stage12-foundations.json').write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
    return report

if __name__ == '__main__':
    if len(sys.argv)!=2: raise SystemExit(__doc__)
    report=generate(load_rom(Path(sys.argv[1])))
    print('stage 12:',report['room_count'],'static maps,',len(report['secret_passages']),'secret passages; raw channel flags:',report['spawn_flags_rom']['room_flags'])
