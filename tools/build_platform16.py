#!/usr/bin/env python3
"""Moving platform of stages 5 and 10 in the 16-bit art (research/gfx16.md): the platform of the NES
game as Castlevania-MD draws it (block 4, sprite tile 390 with palette 2, repeated four times for
32 px), in the 16 x 16 cell of the MSX platform (two cells per platform). Its top row goes on row 1
of the cell, like the MSX pattern (row 0 is empty); the rest of the cell is transparent. Palette 2
of that block is the 16-bit Simon palette, so the colours are entries of vk_simon16_palette (PAL3).

usage: build_platform16.py <castlevania-md checkout>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def array(src, name):
    m = re.search(r'const u(?:16|32) ' + name + r'\[\d+\] = \{(.*?)\};', src, re.S)
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]


def simon16_palette():
    src = (ROOT / 'sgdk/src/generated/simon16_md.c').read_text()
    m = re.search(r'vk_simon16_palette\[16\] = \{(.*?)\};', src, re.S)
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]


def main():
    src = (Path(sys.argv[1]) / 'src/block4.c').read_text()
    tiles, palette = array(src, 'block4_tiles'), array(src, 'block4_palette')
    simon = simon16_palette()
    index = {0: 0}
    for c in range(1, 16):
        colour = palette[32 + c]
        if colour in simon[1:14]:
            index[c] = simon.index(colour, 1)
    rows = []
    for r in range(8):
        word, line = tiles[390 * 8 + r], []
        for x in range(8):
            c = (word >> (28 - 4 * x)) & 15
            if c not in index:
                sys.exit(f'colour {c} of the platform is not in the 16-bit Simon palette')
            line.append(index[c])
        rows.append(line)
    pix = [[0] * 16 for _ in range(16)]
    for y in range(8):
        pix[1 + y] = rows[y] + rows[y]
    words = []
    for c in range(2):          # sprite cells column by column: top left, bottom left, top right, bottom right
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
    out = ROOT / 'sgdk/src/generated'
    (out / 'platform16_md.h').write_text(f"""/* Generated by tools/build_platform16.py. */
#ifndef VK_PLATFORM16_MD_H
#define VK_PLATFORM16_MD_H
#include <genesis.h>
#define VK_PLATFORM16_TILE_COUNT {len(words) // 8}
extern const u32 vk_platform16_tiles[{len(words)}];
#endif
""")
    body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
    (out / 'platform16_md.c').write_text('/* Generated by tools/build_platform16.py. */\n'
                                         '#include "platform16_md.h"\n'
                                         f'const u32 vk_platform16_tiles[{len(words)}] = {{{body}\n}};\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
