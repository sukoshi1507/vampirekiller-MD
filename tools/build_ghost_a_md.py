#!/usr/bin/env python3
"""Sprites of the object 1A released by the candles and blocks of object 15 in the stages 4 to 6 (research/stage9-candle-object.md), in the
layout of the type 5 block (a cell is four tiles, column by column). It is the same image as the object 1C of the stages 7 to 9 (the
masks of the patterns are equal in every room, whatever the pose base 9B, 9D or 9F of the room puts them at in VRAM), but its two
sprite layers are colour 15 (not 14) and colour 2 with CC (OR), the same on the 16 lines of every sprite (colour table of the SAT).
Read in a VRAM snapshot of an openMSX run (snaps/*.vram and *.txt, taken while the object walks; the runs are not versioned):
  odd pose (9F, 9D, 9B)   patterns 70 (colour 15) + 78 (colour 2) in the room 0 of the stage 4 (pose 9F)
  even pose (A0, 9E, 9C)  patterns 74 + 7C
The cells go to 70 and 74 (stages 4 and 5) or 80 and 84 (stage 6) of the enemy block (free there), see Enemies_ghostCell.
Usage: build_ghost_a_md.py SNAPSHOT_BASENAME (without .vram / .txt)
"""
import sys
from pathlib import Path

base = Path(sys.argv[1])
vram = base.with_suffix('.vram').read_bytes()
regs = base.with_suffix('.txt').read_text().split('\n')[0].split()[1:]
sprites = (int(regs[6]) & 0x3F) << 11
words = []
for a, b in ((0x70, 0x78), (0x74, 0x7C)):
    pix = [[0] * 16 for _ in range(16)]
    for pattern, colour in ((a, 15), (b, 2)):
        at = sprites + pattern * 8
        for y in range(16):
            row = (vram[at + y] << 8) | vram[at + 16 + y]
            for x in range(16):
                if row & (0x8000 >> x):
                    pix[y][x] |= colour
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'ghost_a_md.h').write_text(f"""/* Generated by tools/build_ghost_a_md.py. */
#ifndef VK_GHOST_A_MD_H
#define VK_GHOST_A_MD_H
#include <genesis.h>
#define VK_GHOST_A_TILE_COUNT 8   /* two cells of four tiles */
extern const u32 vk_ghost_a_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'ghost_a_md.c').write_text('/* Generated by tools/build_ghost_a_md.py. */\n#include "ghost_a_md.h"\n'
                                  f'const u32 vk_ghost_a_tiles[{len(words)}] = {{{body}\n}};\n')
print(len(words) // 8, 'tiles')
