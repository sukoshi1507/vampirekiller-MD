#!/usr/bin/env python3
"""Copy the 16-bit introduction of Castlevania-MD into sgdk/src/generated/intro16_md.c/.h (once).

usage: import_intro16.py <castlevania-md checkout>

Castlevania-MD (same author) replays the NES introduction (Simon walks to the castle gate, bats fly
by) in the 16-bit art (tiles redrawn by Fiuke Bnuy, given to the author): src/screens.c there, made by
its tools/screens_to_md.py, holds the picture (tiles, 4 palettes, 32 x 30 cells) and the 8x16 sprites
of each of its 458 frames. The data is copied as is, adapted to this port's screen:
- the picture's rows 1..28 only (Castlevania-MD hides the first NES row by a vertical scroll of 8);
- sprite X minus 32 (its 320-pixel screen shows the NES picture 32 pixels to the right);
- the NES status bar left out (5 rows of cells, and the sprites drawn in them).
With the 16-bit graphics option, this introduction replaces the MSX one (research/gfx16.md).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NES_X = 32
HUD_ROWS = 5                     # screen rows of the NES status bar


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = (Path(sys.argv[1]) / 'src/screens.c').read_text()

    def body(name):
        m = re.search(r'const \w+ %s\[\d*\] = \{(.*?)\};' % name, src, re.S)
        return m.group(1)

    def numbers(name):
        return [int(x, 0) for x in re.findall(r'-?0x[0-9A-Fa-f]+|-?\d+', body(name))]
    tiles, palette, cells = numbers('intro_tiles'), numbers('intro_palette'), numbers('intro_map')
    sprites = [tuple(int(v, 0) for v in e.split(',')) for e in re.findall(r'\{([^{}]+)\}', body('intro_sprites'))]
    lists = [tuple(int(v, 0) for v in e.split(',')) for e in re.findall(r'\{([^{}]+)\}', body('intro_lists'))]
    frames = numbers('intro_frames')
    assert len(tiles) % 8 == 0 and len(palette) == 64 and len(cells) == 960
    assert all(first + count <= len(sprites) for first, count in lists) and max(frames) < len(lists)
    cells = cells[32:29 * 32]
    # The NES status bar (score, time, hearts) is not this game's: its rows are emptied and its
    # sprites (the heart) dropped.
    cells[:HUD_ROWS * 32] = [0] * (HUD_ROWS * 32)
    kept, new_lists = [], []
    for first, count in lists:
        mine = [sp for sp in sprites[first:first + count] if sp[1] >= HUD_ROWS * 8]
        new_lists.append((len(kept), len(mine)))
        kept += mine
    sprites, lists = kept, new_lists
    most = max(count for _, count in lists)
    c = ['/* Generated by tools/import_intro16.py from Castlevania-MD (16-bit introduction). Never hand edit. */',
         '#include "intro16_md.h"', '',
         f'const u32 vk_intro16_tiles[{len(tiles)}] = {{']
    c += ['    ' + ','.join(f'0x{v:08X}' for v in tiles[i:i + 8]) + ',' for i in range(0, len(tiles), 8)]
    c += ['};', 'const u16 vk_intro16_palette[64] = {' + ','.join(f'0x{v:04X}' for v in palette) + '};',
          f'const u16 vk_intro16_map[{len(cells)}] = {{']
    c += ['    ' + ','.join(f'0x{v:04X}' for v in cells[i:i + 32]) + ',' for i in range(0, len(cells), 32)]
    c += ['};', f'const VKIntro16Sprite vk_intro16_sprites[{len(sprites)}] = {{']
    c += ['    ' + ','.join(f'{{{x - NES_X},{y},0x{a:04X}}}' for x, y, a in sprites[i:i + 8]) + ','
          for i in range(0, len(sprites), 8)]
    c += ['};', f'const VKIntro16List vk_intro16_lists[{len(lists)}] = {{']
    c += ['    ' + ','.join(f'{{{f},{n}}}' for f, n in lists[i:i + 16]) + ',' for i in range(0, len(lists), 16)]
    c += ['};', f'const u16 vk_intro16_frames[VK_INTRO16_FRAMES] = {{']
    c += ['    ' + ','.join(str(v) for v in frames[i:i + 32]) + ',' for i in range(0, len(frames), 32)]
    c += ['};']
    h = f'''/* Generated by tools/import_intro16.py (research/gfx16.md): the NES introduction in the 16-bit art.
 * Picture: VK_INTRO16_TILES tiles, 4 palettes, 32 x 28 cells (tile offset and palette bits).
 * Frame f: the VK_INTRO16_SPRITE_MAX or fewer 8x16 sprites of vk_intro16_lists[vk_intro16_frames[f]],
 * attr = tile offset and attributes. */
#ifndef VK_INTRO16_MD_H
#define VK_INTRO16_MD_H
#include <genesis.h>
#define VK_INTRO16_TILES {len(tiles) // 8}
#define VK_INTRO16_FRAMES {len(frames)}
#define VK_INTRO16_SPRITE_MAX {most}
typedef struct {{ s16 x, y; u16 attr; }} VKIntro16Sprite;
typedef struct {{ u16 first; u8 count; }} VKIntro16List;
extern const u32 vk_intro16_tiles[{len(tiles)}];
extern const u16 vk_intro16_palette[64];
extern const u16 vk_intro16_map[{len(cells)}];
extern const VKIntro16Sprite vk_intro16_sprites[{len(sprites)}];
extern const VKIntro16List vk_intro16_lists[{len(lists)}];
extern const u16 vk_intro16_frames[VK_INTRO16_FRAMES];
#endif
'''
    out = ROOT / 'sgdk/src/generated'
    (out / 'intro16_md.c').write_text('\n'.join(c) + '\n')
    (out / 'intro16_md.h').write_text(h)
    print(f'{len(tiles) // 8} tiles, {len(frames)} frames, {len(sprites)} sprites (at most {most} a frame)')


if __name__ == '__main__':
    main()
