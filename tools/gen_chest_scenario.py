#!/usr/bin/env python3
"""Writes tests/md_scenarios/zzz_chests_stage1_9.txt : opens the 31 fixed chests of the stages 1 to 9 (generated
`vk_fixed_object_defs`, object 0x19) in the port and compares, for each, the content effect and the delay from the
opening to the pickup with the openMSX traces of research/chests-stage1-9.md.

MSX values (trace, 31 chests, one gold key put in C700, Simon next to the chest, god mode on the port):
  content   effect read in RAM after the pickup
  02        C417 + 5                          03   C701 bit 4, C441 = 10h
  04        C701 bit 5, C441 = 10h            05   C43E = 18h (flash)
  09        C434 = 96h                        0A   C701 bit 6
  0C        C431 bit 3                        0D   C431 bit 4
  0F        C431 bit 6, C701 bit 7, C70F = 3  10   C702 bit 6
  11        C702 bit 7                        13   score + 5000
  1A        C416 = 1                          1C   C416 = 3, C440 = 96h
  1E        C701 bit 3
Delay: the pickup comes 73 frames after the opening (sound 11 at t, sound 12 at t + 73-74), 64 of them the content
waits above the chest (type 05), then 4 + 2 + 2 frames to fall, be fixed and become pickable (types 02, 03, 04, 84).

Usage: gen_chest_scenario.py > tests/md_scenarios/zzz_chests_stage1_9.txt   (run from the repository root)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROOMS = {1: 8, 2: 6, 3: 6, 4: 6, 5: 6, 6: 6, 7: 8, 8: 8, 9: 9}
BOOT = """until front_mode == MODES['TITLE'] max 2000
wait 10
tap C
wait 40
tap START
wait 10
tap UP
tap UP
tap DOWN
tap DOWN
tap LEFT
tap RIGHT
tap LEFT
tap RIGHT
tap B
tap A
wait 4
tap A
expect ram8('Enemies_god') == 0
"""
PAUSE = """until game.player.mode == 0 max 300
wait 30
tap START
wait 10
tap UP
tap UP
tap DOWN
tap DOWN
tap LEFT
tap RIGHT
tap LEFT
tap RIGHT
tap B
tap A
wait 4
"""
C431, C701, C702, C70F, WEAP, HEARTS = 'ram8("vk_candles+320")', 'ram8("vk_candles+322")', 'ram8("vk_candles+330")', 'ram8("vk_candles+329")', \
    'ram8("vk_candles+120")', 'ram8("vk_candles+118")'
KILL, SPAWN, ARMOR, FLASH = 'ram8("vk_enemies+143")', 'ram8("vk_enemies+145")', 'ram8("vk_enemies+146")', 'ram8("vk_enemies+151")'
EFFECT = {
    0x02: HEARTS + ' == 5',
    0x03: '(%s & 0x10) == 0x10 and %s == 0x10' % (C701, ARMOR),
    0x04: '(%s & 0x20) == 0x20 and %s == 0x10' % (C701, ARMOR),
    0x05: FLASH + ' >= 0x16',
    0x09: KILL + ' >= 0x94',
    0x0A: '(%s & 0x40) == 0x40' % C701,
    0x0C: '(%s & 0x08) == 0x08' % C431,
    0x0D: '(%s & 0x10) == 0x10' % C431,
    0x0F: '(%s & 0x40) == 0x40 and (%s & 0x80) == 0x80 and %s == 3' % (C431, C701, C70F),
    0x10: '(%s & 0x40) == 0x40' % C702,
    0x11: '(%s & 0x80) == 0x80' % C702,
    0x13: 'ram32("vk_hud_score") - s0 == 5000',
    0x1A: WEAP + ' == 1',
    0x1C: WEAP + ' == 3 and %s >= 0x94' % SPAWN,
    0x1E: '(%s & 0x08) == 0x08' % C701,
}


def chests():
    src = (ROOT / 'sgdk/src/generated/candles_md.c').read_text()
    a = src.index('vk_fixed_object_defs')
    for m in re.finditer(r'\{ (\d+), (\d+), 0, 0x19, 0x([0-9A-F]+) \},\s+/\* stage (\d+) room (\d+)', src[a:]):
        yield int(m[4]), int(m[5]), int(m[1]), int(m[2]), int(m[3], 16)


def main():
    out = ['# (zzz) The 31 fixed chests of the stages 1 to 9: effect of the content and delay opening -> pickup (generated by tools/gen_chest_scenario.py,',
           '# values of the openMSX traces, research/chests-stage1-9.md).', BOOT.rstrip()]
    cur = None
    for (st, rm, x, y, c) in chests():
        if cur is None:
            out.append(('tap DOWN\n' * (st - 2)).rstrip() if st > 2 else ('tap UP\n' * (2 - st)).rstrip())
        else:
            out.append(PAUSE.rstrip())
            if st != cur[0]:
                out.append('\n'.join(['tap DOWN'] * (st - cur[0])))
            else:
                out.append('tap DOWN\ntap UP' if st != 1 else 'tap UP\ntap DOWN')
        out.append('\n'.join(['tap RIGHT'] * rm + ['tap B']))
        cur = (st, rm)
        out.append('until game.stage == %d and game.room == %d max 300' % (st, rm))
        out.append('poke Enemies_god 1')
        for off in (320, 322, 330, 329, 120, 118, 321):
            out.append('poke vk_candles+%d 0' % off)
        for off in (143, 144, 145, 146, 151):
            out.append('poke vk_enemies+%d 0' % off)
        out.append('wait 20\npoke vk_candles+119 1\nset s0 ram32("vk_hud_score")')
        out.append('poke vk_game+0 %d\npoke vk_game+1 %d' % (x + 8, y + 16))
        out.append('until ram8("vk_candles+119") == 0 max 200\nset t0 frame')
        out.append('until ram8("vk_candles+321") == %d max 200' % c)
        out.append('set dt frame - t0\nwait 2')
        out.append('expect %s # stage %d room %d: content %02X taken' % (EFFECT[c], st, rm, c))
        out.append('expect 72 <= dt <= 76 # delay opening -> pickup (MSX: sound 11 -> sound 12 in 73 frames)')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
