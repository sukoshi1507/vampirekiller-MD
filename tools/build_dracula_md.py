#!/usr/bin/env python3
"""Execute stage18 loaders5780/57B4 and6445; generate sprite cells, both forms."""
import argparse
from probe import ROOT,load_rom,reference_rom
from build_boss12_md import BossGraphics

def generate():
 h=BossGraphics(load_rom(reference_rom()));m=h.cpu;mem=m.memory
 mem[0xD000]=18;mem[0xD001]=9;mem[0xD002]=5;mem[0xCE00]=6;mem[0xF0F1:0xF0F4]=bytes([1,2,3]);h.call(0x5768);h.call(0x5780);assert any(h.vram[0xFF80:0xFFA0]) and any(h.vram[0xFFA0:0xFFC0])
 poses=[];words=[];dedup={}
 for phase,t,plist in [(0,17,[0x56,0x58,0x5B,0x5C,0x5D,0x5E]),(0,45,[0x57,0x59]),(0,46,[0x5A]),(0,5,[3]),(0,12,[0x85,0x86]),(1,12,[0x85,0x86]),(1,44,[2,0xA5,0xA6,0xA7,27,28,29,30,31,32]),(1,30,[0x85,0x86])]:
  if phase and not poses[-1][0]:
   h.call(0x57B4)
  for pose in plist:
   m.set_memory_block(0xC800,bytes(896));m.set_memory_block(0xD700,bytes(1024))
   for a in range(0xD600,0xD700,4):mem[a]=224
   mem[0xCE12]=0
   if t in (5,12):m.a=17 if t==5 else 255;m.bc=0x80A0;m.hl=m.de=0;h.call(0x9F6D);base=0xD700
   else:m.c=t;m.de=0x80A0;h.call(0x5F1D);base=0xC800
   m.ix=base
   if t==17 and pose>=0x5B:h.call(0xAD45)
   mem[base+11]=pose;h.call(0x6445);cells=[]
   for k in range(0,mem[base+32],2):
    a=base+34+5*k
    if not((mem[a+3]|mem[a+8])&15):continue
    dy=(mem[a]-160+128)%256-128;dx=(mem[a+1]-128+128)%256-128
    pixels=[[0]*16 for _ in range(16)]
    for b in (a,a+5):
     pattern,col=mem[b+2],mem[b+3]&15
     for y in range(16):
      address=0xF800+8*pattern;bits=256*h.vram[address+y]+h.vram[address+y+16]
      for x in range(16):
       if bits&(0x8000>>x):pixels[y][x]|=col
    tile=[]
    for c in range(2):
     for r in range(2):
      for y in range(8):
       value=0
       for x in range(8):value=value*16+pixels[8*r+y][8*c+x]
       tile.append(value)
    key=tuple(tile)
    if key not in dedup:dedup[key]=len(words)//8;words.extend(tile)
    cells.append((dy,dx,mem[a+2],dedup[key]))
   poses.append((phase,t,pose,cells))
 layout='/* Generated by tools/build_dracula_md.py via5780/57B4/6445. */\n#ifndef VK_DRACULA_POSES_H\n#define VK_DRACULA_POSES_H\ntypedef struct {signed char dy,dx;unsigned char pattern;unsigned short tile;} VKDraculaCell;\ntypedef struct {unsigned char phase,type,pose,count;VKDraculaCell cell[4];} VKDraculaPose;\n'
 layout+=f'static const VKDraculaPose vk_dracula_poses[{len(poses)}]={{\n'
 for phase,t,pose,cells in poses:
  layout+=' {'+f'{phase},{t},{pose},{len(cells)},'+'{'+','.join('{'+','.join(map(str,c))+'}' for c in cells)+'}},\n'
 layout+='};\n#endif\n'
 header=f'/* Generated by tools/build_dracula_md.py. */\n#ifndef VK_DRACULA_MD_H\n#define VK_DRACULA_MD_H\n#include <genesis.h>\n#define VK_DRACULA_TILE_COUNT {len(words)//8}\nextern const u32 vk_dracula_tiles[{len(words)}];\n#endif\n'
 data='/* Generated by tools/build_dracula_md.py. */\n#include "dracula_md.h"\nconst u32 vk_dracula_tiles['+str(len(words))+']={\n'+''.join(' '+','.join(f'0x{v:08X}' for v in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'
 return {'dracula_poses.h':layout,'dracula_md.h':header,'dracula_md.c':data}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 for name,s in generate().items():
  dest=ROOT/'sgdk/src/generated'/name
  if a.check:assert dest.read_text()==s,name
  else:dest.write_text(s)
 print('Dracula sprites: 26 poses, loaders and composed cells','CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
