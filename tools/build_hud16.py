#!/usr/bin/env python3
"""HUD and text in the 16-bit graphics mode (research/gfx16.md, section "HUD et texte 16 bits"): variant B' "acier" of the
mock-up validated by the user (~/Documents/VampireKiller-MD_maquette16_hud.png).

usage: build_hud16.py [--preview FILE.png]

Writes sgdk/src/generated/hud16_md.c/.h. Only PAL1 entries that exist in vk_item16_palette (items16_md.c; the HUD entries
1, 2, 8, 14, 15 are those of the MSX palette) are used: the palette does not change.

- Font: the 64 MSX glyphs, same shapes and layout. The white (14) of the letters keeps the top row, and takes the steel
  entry 10 on rows 1, 2 and 6 and the dark steel entry 3 on row 7 (vk_hud16_steel, one word per row, applied by
  msx_text.c to the font at draw time: no second font in ROM). The heart keeps its colours. No shadow. '<' and '>' (codes
  2C / 2E, unused shapes of the MSX font) are chevrons of the same weight (vk_hud16_chevron).
- Energy bars: the fill rows of the PLAYER and ENEMY bars take a ramp (vk_hud16_player_ramp, vk_hud16_enemy_ramp), the
  outline stays white (hud.c recolours the scene 6 tiles once).
- Boxes: the frames of the three boxes keep their white / red 1 px line, with a bevel in entry 3 on the right column and the
  bottom line of the white boxes. hud.c draws the cells of the top, bottom and right edges with vk_hud16_frame_tiles
  (5 tiles: red top, white top, bevel bottom, bevel corner, bevel edge); item_view.c bevels the box cells it loads.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / 'sgdk/src/generated'

STEEL = {1: 10, 2: 10, 6: 10, 7: 3}          # font row -> PAL1 entry (the other rows stay white, 14)
PLAYER_RAMP = (1, 1, 9, 7)                   # the 4 fill rows of the PLAYER bar (entry 1 = the MSX fill colour)
ENEMY_RAMP = (8, 8, 5, 4)                    # ... of the ENEMY bar
BEVEL = 3
RED, WHITE = 8, 14
CHEVRON = ["........", "........", "....##..", "...##...", "..##....", "...##...", "....##..", "........"]


def row_word(colours):
    w = 0
    for c in colours:
        w = (w << 4) | c
    return w


def chevrons():
    out = []
    for flip in (0, 1):
        for r in CHEVRON:
            r = r[::-1] if flip else r
            out.append(row_word([WHITE if ch == '#' else 0 for ch in r]))
    return out


def frame_tiles():
    """Tiles of the frame cells that hud.c draws (the others are the bar tiles and the box cells of item_view.c).
    The bottom of a red box is the red top flipped vertically (line 3 -> line 4); the corner of the right box flipped too."""
    z = [0] * 8
    t = [list(z) for _ in range(5)]
    t[0][3] = row_word([RED] * 8)                     # red box, top line (y 11)
    t[1][3] = row_word([WHITE] * 8)                   # white box, top line
    t[2][4] = row_word([BEVEL] * 8)                   # white box, bottom line (y 28) in the bevel colour
    for line in range(3, 8):
        t[3][line] = BEVEL << 28                      # right edge, top corner (x 248, lines 3..7; flipped: bottom)
    t[4] = [BEVEL << 28] * 8                          # right edge
    return [w for tile in t for w in tile]


def steel_words():
    return [row_word([STEEL[r]] * 8) if r in STEEL else 0 for r in range(8)]


def entries_used():
    return set(STEEL.values()) | set(PLAYER_RAMP) | set(ENEMY_RAMP) | {BEVEL, RED, WHITE}


def fmt(vals, per, width):
    f = '0x%%0%dXUL' % width if width == 8 else '%d'
    return '\n'.join('    ' + ','.join(f % v for v in vals[i:i + per]) + ',' for i in range(0, len(vals), per))


def render():
    words_frame, words_chev, words_steel = frame_tiles(), chevrons(), steel_words()
    h = ['/* Generated by tools/build_hud16.py (research/gfx16.md, "HUD et texte 16 bits"). PAL1 entries of the 16-bit mode. */',
         '#ifndef VK_HUD16_MD_H', '#define VK_HUD16_MD_H', '#include <genesis.h>',
         '/* Cells of the frame of the boxes: red top, white top, white bottom (bevel), bevel corner (lines 3..7), bevel edge. */',
         '#define VK_HUD16_FRAME_TILES 5',
         '/* PAL1 entry of the bevel (right column and bottom line of the white boxes). */',
         '#define VK_HUD16_BEVEL %d' % BEVEL,
         'extern const u32 vk_hud16_frame_tiles[%d];' % len(words_frame),
         '/* Chevrons of "<" and ">" (8 rows each). */',
         'extern const u32 vk_hud16_chevron[%d];' % len(words_chev),
         '/* Per font row: the steel colour of the letters (a word of 8 pixels), 0 = white kept. */',
         'extern const u32 vk_hud16_steel[8];',
         '/* Colour of each of the 4 fill rows of the PLAYER and ENEMY bars. */',
         'extern const u8 vk_hud16_player_ramp[4];', 'extern const u8 vk_hud16_enemy_ramp[4];',
         '#endif']
    c = ['/* Generated by tools/build_hud16.py. */', '#include "hud16_md.h"',
         'const u32 vk_hud16_frame_tiles[%d] = {\n%s\n};' % (len(words_frame), fmt(words_frame, 8, 8)),
         'const u32 vk_hud16_chevron[%d] = {\n%s\n};' % (len(words_chev), fmt(words_chev, 8, 8)),
         'const u32 vk_hud16_steel[8] = {\n%s\n};' % fmt(words_steel, 4, 8),
         'const u8 vk_hud16_player_ramp[4] = {%s};' % ','.join(map(str, PLAYER_RAMP)),
         'const u8 vk_hud16_enemy_ramp[4] = {%s};' % ','.join(map(str, ENEMY_RAMP))]
    return '\n'.join(h) + '\n', '\n'.join(c) + '\n', 4 * (len(words_frame) + len(words_chev) + 8) + 8


def nums(path, name):
    m = re.search(name + r'\[[^\]]*\]\s*=\s*\{(.*?)\};', path.read_text(), re.S)
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', m.group(1))]


def preview(path):
    from PIL import Image
    pal = nums(GEN / 'items16_md.c', 'vk_item16_palette')
    assert all(pal[i] for i in entries_used() - {2}), 'entry missing in PAL1'
    rgb = [((p & 0xE) * 17, ((p >> 4) & 0xE) * 17, ((p >> 8) & 0xE) * 17) for p in pal]
    font = nums(GEN / 'object_tiles_md.c', 'vk_msx_font_tiles')
    steel = steel_words()
    im = Image.new('RGB', (256, 90), (0, 0, 0))

    def put(x, y, v):
        if v and 0 <= x < 256 and 0 <= y < 90:
            im.putpixel((x, y), rgb[v] if v != 2 else (0, 0, 0))

    def text(x, y, s):
        for k, ch in enumerate(s):
            code = 0x30 if ch == '-' else (ord(ch) - 0x10)
            if ch == '<' or ch == '>':
                g = chevrons()[(ch == '>') * 8:(ch == '>') * 8 + 8]
            else:
                g = font[(code - 0x20) * 8:(code - 0x20) * 8 + 8]
            for r in range(8):
                w = g[r]
                if steel[r] and code != 0x50:
                    m = (w >> 1) & 0x11111111
                    m |= (m << 1) | (m << 2) | (m << 3)
                    w = m & steel[r]
                for p in range(8):
                    put(x + 8 * k + p, y + r, (w >> (28 - 4 * p)) & 15)

    text(8, 0, "SCORE-000000")
    text(108, 0, "STAGE-01")
    text(176, 0, "`-00")
    text(212, 0, "P-02")
    text(8, 12, "PLAYER")
    text(8, 20, "ENEMY")
    for y0, ramp in ((13, PLAYER_RAMP), (22, ENEMY_RAMP)):
        for x in range(59, 125):
            put(x, y0, WHITE)
            put(x, y0 + 5, WHITE)
        for y in range(y0, y0 + 6):
            put(59, y, WHITE)
            put(124, y, WHITE)
        for k, v in enumerate(ramp):
            for x in range(60, 124):
                put(x, y0 + 1 + k, v)
    for x in range(127, 145):
        put(x, 11, RED)
        put(x, 28, RED)
    for y in range(11, 29):
        put(127, y, RED)
        put(144, y, RED)
    for x0, x1 in ((147, 180), (183, 248)):
        for x in range(x0, x1 + 1):
            put(x, 11, WHITE)
            put(x, 28, BEVEL)
        for y in range(11, 29):
            put(x0, y, WHITE)
            put(x1, y, BEVEL)
    text(72, 40, ": KONAMI 1986")
    text(80, 52, "PRESS START")
    text(72, 64, "SOUND < PSG >")
    text(72, 76, "GRAPH < 16B >")
    im.resize((768, 270), Image.NEAREST).save(path)


def main():
    h, c, size = render()
    (GEN / 'hud16_md.h').write_text(h)
    (GEN / 'hud16_md.c').write_text(c)
    print('hud16: %d B of data, PAL1 entries %s' % (size, sorted(entries_used())))
    if '--preview' in sys.argv:
        preview(sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()
