#!/usr/bin/env python3
"""Sprites of the stage 9 boss: the two walkers (object 14h, poses 33 to 38, a column of three 16 x 16 cells) and their
fireball (D700 type 7, poses 39 and 3A). The patterns are compressed in the ROM (46F1), so they are read from the VRAM
snapshots of openMSX runs (scratchpad/stage9/out/R, C2 and C, not versioned; see research/stage9-boss.md): a snapshot holds
the C800 blocks of the two objects (their pose and place) and the SAT, which says which patterns draw each cell.
Each cell is two sprite layers: pattern N in colour 2, then pattern N + 4 in colour 4C (colour 12 with the CC bit, OR-ed);
a cell of a blinking walker (state 3) has colour 08 for the second layer, without CC (the first layer wins).
The fireball is two sprites, pattern N + 4 in colour 5 first, then pattern N in colour 42 (2 with CC): OR 7 where both.
Tiles: cell (pose - 33) * 3 + part, 4 tiles per cell (column by column), then the fireball cells 39 and 3A.
Usage: build_boss9_md.py RUN...   (directories holding snaps/*.vram and *.txt)
"""
import collections, glob, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'sgdk/src/generated'
votes = collections.defaultdict(collections.Counter)      # (pose, part) -> (rows of layer 1, rows of layer 2)
fire = collections.defaultdict(collections.Counter)       # pose -> (rows of N, rows of N + 4)


def rows(vram, gen, pattern):
    a = gen + pattern * 8
    return tuple((vram[a + r] << 8) | vram[a + 16 + r] for r in range(16))


for run in sys.argv[1:]:
    for f in sorted(glob.glob(str(Path(run) / 'snaps' / '*.vram'))):
        base = f[:-5]
        vram = open(f, 'rb').read()
        text = open(base + '.txt').read().split('\n')
        regs = [int(x) for x in text[0].split()[1:]]
        ram = bytes.fromhex([l for l in text if l.startswith('C800')][0].split()[1])
        gen = (regs[6] & 0x3F) << 11
        sat = ((regs[11] & 3) << 15) | ((regs[5] & 0xF8) << 7) | 0x200
        col = sat - 0x200
        spr = []
        for n in range(32):
            y = vram[sat + 4 * n]
            if y == 216:
                break
            spr.append((y, vram[sat + 4 * n + 1], vram[sat + 4 * n + 2], vram[col + 16 * n]))
        objs = [ram[i * 128:i * 128 + 32] for i in range(2)]
        objs = [(o[3], o[5], o[11]) for o in objs if o[0] == 0x14]
        for oy, ox, pose in objs:
            if len([1 for _, x, _ in objs if abs(x - ox) < 14]) > 1:      # the cells of the two walkers would mix
                continue
            for part, dy in enumerate((47, 31, 15)):
                cell = [s for s in spr if s[0] == (oy - dy) & 255 and abs(s[1] - (ox - 8)) <= 4 and s[2] < 0xE0]
                one = [s for s in cell if s[3] == 2]
                two = [s for s in cell if s[3] in (0x4C, 8) and one and s[2] == one[0][2] + 4]
                if len(one) == 1 and len(two) == 1:
                    votes[(pose, part)][(rows(vram, gen, one[0][2]), rows(vram, gen, two[0][2]))] += 1
        # fireballs: the pairs (N + 4 colour 5, N colour 42), N = 80 (pose 39) or 88 (pose 3A)
        for i in range(len(spr) - 1):
            a, b = spr[i], spr[i + 1]
            if a[3] == 5 and b[3] == 0x42 and a[2] == b[2] + 4 and b[2] in (0x80, 0x88) and a[0] == b[0] and a[1] == b[1]:
                fire[0x39 if b[2] == 0x80 else 0x3A][(rows(vram, gen, b[2]), rows(vram, gen, a[2]))] += 1


def tiles(pix, cols, rws):
    out = []
    for c in range(cols):
        for r in range(rws):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                out.append(v)
    return out


def compose(l1, l2, c1, c2):
    pix = [[0] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            m = 0x8000 >> x
            pix[y][x] = (c1 if l1[y] & m else 0) | (c2 if l2[y] & m else 0)
    return pix


words, report = [], []
for pose in range(0x33, 0x39):
    for part in range(3):
        c = votes[(pose, part)]
        assert c, f'no snapshot for pose {pose:02X} part {part}'
        (l1, l2), n = c.most_common(1)[0]
        report.append(f'{pose:02X}.{part}: {n}/{sum(c.values())}')
        words += tiles(compose(l1, l2, 2, 12), 2, 2)
for pose in (0x39, 0x3A):
    c = fire[pose]
    assert c, f'no snapshot for fireball {pose:02X}'
    (l1, l2), n = c.most_common(1)[0]
    report.append(f'{pose:02X}: {n}/{sum(c.values())}')
    words += tiles(compose(l1, l2, 2, 5), 2, 2)
print(' '.join(report))
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(OUT / 'boss9_md.h').write_text(f"""/* Generated by tools/build_boss9_md.py from openMSX VRAM snapshots. */
#ifndef VK_BOSS9_MD_H
#define VK_BOSS9_MD_H
#include <genesis.h>
#define VK_BOSS9_TILE_COUNT {len(words) // 8}
extern const u32 vk_boss9_tiles[{len(words)}];
#endif
""")
(OUT / 'boss9_md.c').write_text('/* Generated by tools/build_boss9_md.py from openMSX VRAM snapshots. */\n#include "boss9_md.h"\n'
                                f'const u32 vk_boss9_tiles[{len(words)}] = {{{body}\n}};\n')
