#!/usr/bin/env python3
"""Sprites of objects 06 and 08 of stage 4, in the layout of the type 5 block (pattern N is
tile N - 0x40). Patterns come from the VRAM snapshot of an openMSX run (they are compressed
in the ROM, 46F1); colours 2 and 5 of the two CC layers, seen in the SAT. The run is not
versioned, see research/stage4-enemies.md. Usage: build_stage4_enemies_md.py RUN LABEL
"""
import glob, sys
from pathlib import Path

run, label = Path(sys.argv[1]), sys.argv[2]
base = sorted(glob.glob(str(run / 'snaps' / f'*_{label}.vram')))[0][:-5]
vram = open(base + '.vram', 'rb').read()
regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
sprites = (regs[6] & 0x3F) << 11
CELLS = (0x40, 0x48, 0x50, 0x58, 0x80, 0x88, 0x90, 0x98, 0xA0, 0xA8, 0xB0, 0xB8)
words = []
for pattern in range(0x40, 0xC0, 4):
    pix = [[0] * 16 for _ in range(16)]
    if pattern in CELLS:
        for layer, colour in ((pattern, 2), (pattern + 4, 5)):
            a = sprites + layer * 8
            for y in range(16):
                row = (vram[a + y] << 8) | vram[a + 16 + y]
                for x in range(16):
                    if row & (0x8000 >> x):
                        pix[y][x] |= colour
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage4_enemies_md.h').write_text(f"""/* Generated by tools/build_stage4_enemies_md.py. */
#ifndef VK_STAGE4_ENEMIES_MD_H
#define VK_STAGE4_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE4_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage4_enemy_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage4_enemies_md.c').write_text('/* Generated by tools/build_stage4_enemies_md.py. */\n#include "stage4_enemies_md.h"\n'
    f'const u32 vk_stage4_enemy_tiles[{len(words)}] = {{{body}\n}};\n')
print(len(words) // 8, 'tiles', {hex(p): sum(1 for r in range(16) if vram[sprites + p * 8 + r] or vram[sprites + p * 8 + 16 + r]) for p in CELLS})
