#!/usr/bin/env python3
"""Vectors for tests/test_dragon.c : the object 0E of the stage 11 room 5 (init AACD, routine A9B7, then 99B9 and 99E5) and its shot (D700 type 1 made by A0E5 and
9F6D, then 9E58, 99B9 and 99E5), run pass by pass by the original Z80 routines in the kosarev/z80 emulator on the map of the stage 11 room 5, Simon moved by a scripted
triangle wave. LD A,R (AA81) is replaced by LD A,n (the port reads Enemies_s7R). Also the aim A0E5 alone for a grid of positions.
A row is (state +1, X +5, Y +3, +C, +18, +19, targets +10..+17 (8), entries Y, X, pattern, colour for the 8 SAT entries at +22 (32), D700 block 0 : type, X, Y, vx, vy, +C)
after the pass. Usage: gen_dragon_vectors.py ROM OUT.h"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from castle_room_objects import make_machine, call
from probe import load_rom

PASSES = 400
# R, difficulty D012, Simon X (low, high, step per pass), Simon Y
SCENARIOS = [
    (0, 0, 16, 16, 0, 176), (5, 0, 16, 120, 1, 176), (9, 0, 100, 100, 0, 112), (15, 0, 20, 230, 2, 144), (3, 1, 16, 16, 0, 176),
    (12, 2, 40, 200, 3, 176), (7, 0, 130, 200, 1, 80), (1, 0, 220, 240, 1, 176), (8, 3, 16, 100, 2, 112), (2, 0, 60, 60, 0, 40),
]
AIMS = [(dx, dy, sx, sy, d) for dx in (160, 168, 200) for dy in (112, 124, 128) for sx in (8, 40, 100, 150, 190, 230) for sy in (40, 112, 144, 176) for d in (0, 2)]


def build(data, R, difficulty):
    data = bytearray(data)
    off = 0x6000 + 0xAA81 - 0xA000
    assert data[off:off + 2] == b'\xED\x5F'
    data[off:off + 2] = bytes((0x3E, R))
    m = make_machine(bytes(data))
    mem = m.memory
    mem[0xD000] = 11; mem[0xD001] = 5; mem[0xD002] = data[0x1E6A + 11]; mem[0xC41A] = 0
    call(m, 0x5A49); call(m, 0x5B1B); call(m, 0x4F83)
    for w in range(4):
        m.set_memory_block(0x4000 + w * 8192, bytes(data)[w * 8192:(w + 1) * 8192])
    mem[0xD012] = difficulty; mem[0xC420] = 0; mem[0xCE00] = 0; mem[0xCE03] = 0; mem[0xD010] = 0
    for a in range(0xD600, 0xD700, 4): mem[a] = 0xE0
    for k in range(7):
        for i in range(0x80): mem[0xC800 + 0x80 * k + i] = 0
    for k in range(8):
        for i in range(0x80): mem[0xD700 + 0x80 * k + i] = 0
    return m, bytes(data)


def run(data, R, difficulty, lo, hi, step, sy):
    m, d = build(data, R, difficulty)
    mem = m.memory
    b = 0xC800
    mem[0xC427] = lo; mem[0xC425] = sy
    mem[b] = 0x0E; mem[b + 3] = 112; mem[b + 5] = 208
    mem[b + 0x7E] = 1; mem[b + 0x7F] = 1; mem[b + 0x20] = 8; mem[b + 13] = d[0x20E1 + 0x0E]
    m.ix = b
    call(m, 0xAACD)
    rows = []
    span = max(hi - lo, 0)
    shot = 0
    for p in range(PASSES):
        t = (p * step) % (2 * span) if span else 0
        mem[0xC427] = lo + (2 * span - t if t > span else t)
        m.ix = b
        call(m, 0xA9B7)
        m.ix = b
        call(m, 0x99B9)
        m.ix = b
        call(m, 0x99E5)
        for k in range(8):
            q = 0xD700 + 0x80 * k
            if mem[q]:
                m.ix = q
                call(m, d[0x4000 + 0x9E58 - 0x8000 - 0] if False else 0x9E58)
                m.ix = q
                call(m, 0x99B9)
                m.ix = q
                call(m, 0x99E5)
        row = [mem[b + 1], mem[b + 5], mem[b + 3], mem[b + 12], mem[b + 0x18], mem[b + 0x19]]
        row += [mem[b + 0x10 + i] for i in range(8)]
        for i in range(8):
            e = b + 0x22 + 5 * i
            row += [mem[e], mem[e + 1], mem[e + 2], mem[e + 3]]
        q = 0xD700
        if mem[q]:
            row += [mem[q], mem[q + 5], mem[q + 3], mem[q + 9] | mem[q + 10] << 8, mem[q + 7] | mem[q + 8] << 8, mem[q + 12]]
            shot += 1
        else:
            row += [0, 0, 0, 0, 0, 0]
        rows.append(row)
    return rows


def aim(data, dx, dy, sx, sy, difficulty):
    """A0E5 alone : IX = an object at (X dx, Y dy) (+5, +3), Simon at (sx, sy) : returns (HL, DE) as the shot velocities."""
    m, d = build(data, 0, difficulty)
    mem = m.memory
    b = 0xC800
    mem[b + 3] = dy; mem[b + 5] = dx
    mem[0xC427] = sx; mem[0xC425] = sy
    m.ix = b
    call(m, 0xA0E5)
    return m.hl, m.de


def main():
    data = load_rom(Path(sys.argv[1]))
    out = ["/* Generated by tools/gen_dragon_vectors.py from the reference ROM routines (Z80 emulator). Do not edit. */",
           "typedef struct { int r, difficulty, lo, hi, step, sy, passes, first; } DragonVector;",
           "typedef struct { int dx, dy, sx, sy, difficulty, hl, de; } DragonAim;",
           "#define DRAGON_ROW 52",
           "static const int dragon_rows[] = {"]
    vec, n = [], 0
    shots = 0
    for sc in SCENARIOS:
        rows = run(data, *sc)
        vec.append((sc, len(rows), n))
        prev = None
        for r in rows:
            out.append(" " + ",".join(str(v) for v in r) + ",")
            if r[46] and not (prev and prev[46]): shots += 1
            prev = r
            n += 1
    out.append("};")
    out.append("static const DragonVector dragon_vectors[] = {")
    for sc, c, first in vec:
        out.append(" {%d,%d,%d,%d,%d,%d,%d,%d}," % (*sc, c, first))
    out.append("};")
    out.append("static const DragonAim dragon_aims[] = {")
    for a in AIMS:
        hl, de = aim(data, *a)
        out.append(" {%d,%d,%d,%d,%d,%d,%d}," % (*a, hl, de))
    out.append("};")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(len(vec), 'scenarios', n, 'rows', shots, 'shots', len(AIMS), 'aims')


if __name__ == '__main__':
    main()
