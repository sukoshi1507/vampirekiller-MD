#!/usr/bin/env python3
"""Sprites of the stage 3 boss (object 12h), its fireball and the orb (object 22h).

The patterns are compressed in the ROM (46F1), so they are read from VRAM snapshots of
openMSX runs, as tools/build_door_key_md.py does. Runs: scratchpad/stage3/out/W (fight)
and scratchpad/stage3/out/O (orb), not versioned; see research/stage3-boss.md.
Usage: build_boss_md.py WRUN ORUN
"""
import glob, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
W, O = Path(sys.argv[1]), Path(sys.argv[2])
OUT = ROOT / 'sgdk/src/generated'


def snapshot(run, label):
    base = sorted(glob.glob(str(run / 'snaps' / f'*_{label}.vram')))[0][:-5]
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    return vram, (regs[6] & 0x3F) << 11


def layer(vram, base, pattern):
    """16 rows of 16 bits."""
    a = base + pattern * 8
    return [(vram[a + r] << 8) | vram[a + 16 + r] for r in range(16)]


def cell(layers):
    """layers: (pattern rows, colour), OR of the colours as the CC bit does."""
    pix = [[0] * 16 for _ in range(16)]
    for rows, colour in layers:
        for y in range(16):
            for x in range(16):
                if rows[y] & (0x8000 >> x):
                    pix[y][x] |= colour
    return pix


def tiles(pix, cols, rows):
    """Column by column, as an MD sprite."""
    out = []
    for c in range(cols):
        for r in range(rows):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                out.append(v)
    return out


vram, base = snapshot(W, 'b8')
boss = []
for n in (0x40, 0x48, 0x50, 0x58, 0x60, 0x68, 0x70):
    boss += tiles(cell([(layer(vram, base, n), 1), (layer(vram, base, n + 4), 2)]), 2, 2)
boss += tiles(cell([(layer(vram, base, 0xF0), 8)]), 2, 2)

# Orb: one frame per pose, from the SAT of the run. Falling at 1 px per pass, the SAT
# of a frame is that of the previous pass, hence Y - 1 for poses 90 and 91.
vram, base = snapshot(O, 'orb2')
poses = {}
for line in open(O / 'sat_s2.csv'):
    f = line.rstrip('\n').split(',')
    if len(f) < 12 or f[1] != '5' or not f[11].startswith('22'):
        continue
    o = f[11].split(':')[0]
    pose, y, x = int(o[22:24], 16), int(o[6:8], 16), int(o[10:12], 16)
    if pose in poses or o[2:4] == '02' or not f[10].strip():
        continue
    entries = re.findall(r'(\d+)/([0-9A-F]+):(\d+):(\d+):([0-9A-F]+)', f[10])
    if pose != 0x8F or o[2:4] == '00':
        poses[pose] = (y - (0 if o[2:4] == '00' else 1), x, entries)
orb = []
for pose in (0x8F, 0x90, 0x91):
    y0, x0, entries = poses[pose]
    pix = [[0] * 32 for _ in range(32)]
    for _, p, sy, sx, col in sorted(entries, key=lambda e: -int(e[0])):   # sprite 0 on top
        rows, colour = layer(vram, base, int(p, 16)), int(col, 16) & 15
        for r in range(16):
            for c in range(16):
                if rows[r] & (0x8000 >> c):
                    py, px = int(sy) - (y0 - 16) + r, int(sx) - (x0 - 16) + c
                    if 0 <= py < 32 and 0 <= px < 32:
                        pix[py][px] = colour
    orb += tiles(pix, 4, 4)


def table(name, v):
    body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(v))
    return f'const u32 {name}[{len(v)}] = {{{body}\n}};\n'


(OUT / 'boss_md.h').write_text(f"""/* Generated by tools/build_boss_md.py from openMSX VRAM snapshots. */
#ifndef VK_BOSS_MD_H
#define VK_BOSS_MD_H
#include <genesis.h>
#define VK_BOSS_TILE_COUNT {len(boss) // 8}
#define VK_ORB_TILE_COUNT {len(orb) // 8}
extern const u32 vk_boss_tiles[{len(boss)}];
extern const u32 vk_orb_tiles[{len(orb)}];
#endif
""")
(OUT / 'boss_md.c').write_text('/* Generated by tools/build_boss_md.py from openMSX VRAM snapshots. */\n#include "boss_md.h"\n'
                               + table('vk_boss_tiles', boss) + table('vk_orb_tiles', orb))
print('boss tiles', len(boss) // 8, 'orb tiles', len(orb) // 8, {hex(k): (v[0], v[1], len(v[2])) for k, v in poses.items()})
