#!/usr/bin/env python3
"""Extract stage18 credits pointed to by678E; no inferred text or timing."""
import argparse
from probe import ROOT,load_rom,reference_rom

def generate():
 r=load_rom(reference_rom());lines=[]
 for i in range(42):
  a=0x678E-0x4000+2*i;p=r[a]|r[a+1]<<8;o=8*8192+p-0xA000 if p>=0xA000 else 5*8192+p-0x8000
  timing,x=r[o:o+2];text=[]
  if x!=255:
   j=o+2
   while r[j]!=255:text.append(r[j]);j+=1
  lines.append((timing,x,text))
 out='/* Generated by tools/build_dracula_data.py from ROM678E. */\n#ifndef VK_DRACULA_DATA_H\n#define VK_DRACULA_DATA_H\n'
 out+='static const unsigned char vk_dracula_death_offset[47]={'+','.join(str(v) for v in r[0x9B33-0x4000:0x9B33-0x4000+47])+'};\n'
 out+='static const unsigned char vk_dracula_credit_time[42]={'+','.join(str(t) for t,x,b in lines)+'};\n'
 out+='static const unsigned char vk_dracula_credit_x[42]={'+','.join(str(x) for t,x,b in lines)+'};\n'
 for i,(t,x,b) in enumerate(lines):out+=f'static const unsigned char vk_dracula_credit_{i}[]={{'+','.join(str(c) for c in b+[255])+'};\n'
 out+='static const unsigned char *const vk_dracula_credit_text[42]={'+','.join(f'vk_dracula_credit_{i}' for i in range(42))+'};\n#endif\n'
 return out

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();dest=ROOT/'sgdk/src/generated/dracula_data.h';s=generate()
 if a.check:assert dest.read_text()==s
 else:dest.write_text(s)
 print('Dracula credits: 41 lines and terminal, ROM data','CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
