#!/usr/bin/env python3
"""Tables of the stage map (object 0F) read from the ROM: research/stage-map.md."""
import sys
import argparse
from probe import ROOT,load_rom,reference_rom
from pathlib import Path

STAGES = 19
BANK2 = 0x4000                       # 8000-9FFF of the ROM map at file offset 4000


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rom',nargs='?',type=Path,default=reference_rom())
    parser.add_argument('out',nargs='?',type=Path,default=ROOT/'sgdk/src/generated')
    parser.add_argument('--check',action='store_true');args=parser.parse_args()
    rom = load_rom(args.rom)
    out = args.out
    at = lambda addr, n: rom[addr - BANK2:addr - BANK2 + n]
    counts = at(0x95F6, STAGES)
    assert max(counts)<=12
    rooms = []
    for stage in range(STAGES):
        low, high = at(0x9695 + 2 * stage, 2)
        rooms.append(at(low | high << 8, counts[stage]).ljust(12, b'\0'))
    tables = [
        ('vk_map_room_count', f'[{STAGES}]', counts),
        ('vk_map_rooms', f'[{STAGES}][12]', b''.join(rooms)),
        ('vk_map_place', '[30][2]', at(0x9757, 60)),
        ('vk_map_class', '[14]', at(0x97EC, 14)),
        ('vk_map_d002', f'[{STAGES}]', rom[0x1E6A:0x1E6A + STAGES]),
        ('vk_map_exit', f'[{STAGES}][3]', at(0x98AC, 3 * STAGES)),
        ('vk_map_dot', '[8]', at(0x984B, 8)),
        ('vk_map_arrow', '[2][28]', at(0x9874, 28) + at(0x9890, 28)),
    ]
    head = ['#ifndef VK_STAGE_MAP_MD_H', '#define VK_STAGE_MAP_MD_H', '#include "../player.h"']
    code = ['/* Generated by tools/build_stage_map_md.py. Never hand edit. */', '#include "stage_map_md.h"']
    for name, dims, data in tables:
        head.append(f'extern const VKByte {name}{dims};')
        code.append(f'const VKByte {name}{dims} = {{')
        code.append(nested(data, [int(d) for d in dims[1:-1].split('][')]))
        code.append('};')
    head.append('#endif')
    for name,text in [('stage_map_md.h','\n'.join(head)+'\n'),('stage_map_md.c','\n'.join(code)+'\n')]:
        if args.check:assert (out/name).read_text()==text,name
        else:(out/name).write_text(text)
    print('Stage map:19 ROM tables', 'CHECK PASS' if args.check else 'generated')


def nested(data, dims):
    if len(dims) == 1:
        return ', '.join(f'0x{b:02X}' for b in data)
    return ',\n'.join('{ ' + nested(data[i * dims[1]:(i + 1) * dims[1]], dims[1:]) + ' }'
                      for i in range(dims[0]))


if __name__ == '__main__':
    main()
