#!/usr/bin/env python3
"""Sprites of the stage 6 boss (object 13h), its fireball and the orb (object 22h, stage 6 colours).

The patterns are compressed in the ROM (46F1), so they are read from VRAM snapshots of an openMSX run
(scratchpad/stage6boss/out/C, not versioned; see research/stage6-boss.md), as tools/build_boss_md.py does.
Boss: 8 cells of 16 x 16 (two poses, 2 x 2 cells), each made of two sprite layers (colour 2, then colour 5 with
the CC bit, OR-ed). Fireball: 4 cells (poses 27, 28 leftwards, 29, 2A rightwards), same two layers.
Orb: three poses of 4 layers of the SAT, colours 0E, 08, 07, 02 (B809, stage other than 3).
Usage: build_boss6_md.py scratchpad/stage6boss/out/C r5_70749C98686C787C r5_4C484440   (snapshot labels, without extension)
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUN = Path(sys.argv[1])
OUT = ROOT / 'sgdk/src/generated'


def snapshot(label):
    base = sorted((RUN / 'snaps').glob(f'*_{label}.vram'))[0].with_suffix('')
    vram = open(str(base) + '.vram', 'rb').read()
    regs = [int(x) for x in open(str(base) + '.txt').read().split('\n')[0].split()[1:]]
    sat = ((regs[11] & 3) << 15) | ((regs[5] & 0xF8) << 7) | 0x200
    return vram, (regs[6] & 0x3F) << 11, sat


def layer(vram, base, pattern):
    """16 rows of 16 bits."""
    a = base + pattern * 8
    return [(vram[a + r] << 8) | vram[a + 16 + r] for r in range(16)]


def tiles(pix, cols, rows):
    """Column by column, as an MD sprite."""
    out = []
    for c in range(cols):
        for r in range(rows):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                out.append(v)
    return out


def cell(layers):
    """layers: (pattern rows, colour), OR of the colours as the CC bit does."""
    pix = [[0] * 16 for _ in range(16)]
    for rows, colour in layers:
        for y in range(16):
            for x in range(16):
                if rows[y] & (0x8000 >> x):
                    pix[y][x] |= colour
    return pix


def check_uniform(vram, sat, patterns):
    """The cells assume one colour per sprite: every line of the colour table must carry the same byte."""
    col = sat - 0x200
    seen = {}
    for n in range(32):
        y, pat = vram[sat + 4 * n], vram[sat + 4 * n + 2]
        if y == 216:
            break
        if pat in patterns:
            line = bytes(vram[col + 16 * n:col + 16 * n + 16])
            assert len(set(line)) == 1, (hex(pat), line.hex())
            seen[pat] = line[0]
    return seen


vram, base, sat = snapshot(sys.argv[2])
cells = [(0x40, 0x44), (0x50, 0x54), (0x48, 0x4C), (0x58, 0x5C), (0x60, 0x64), (0x70, 0x74), (0x68, 0x6C), (0x78, 0x7C)]
shots = [(0x84, 0x80), (0x8C, 0x88), (0x94, 0x90), (0x9C, 0x98)]
boss = []
for a, b in cells + shots:
    boss += tiles(cell([(layer(vram, base, a), 2), (layer(vram, base, b), 5)]), 2, 2)
print('colour bytes on screen', {hex(k): hex(v) for k, v in check_uniform(vram, sat, {p for c in cells + shots for p in c}).items()})

# Orb: one frame per pose. The SAT of a frame is that of the previous pass (research/frame-timing.md), so the layers
# of a pose are read from the rows whose object of two frames before (one pass) has that pose, in the landed state:
# the object sits at (78h, B0h) and the three poses use three sets of four patterns (4C 48 44 40, 50 4C 48 44, 50 58 54 40).
vram, base, sat = snapshot(sys.argv[3])
rows = {}
for line in open(RUN / 'sat_s2.csv'):
    f = line.rstrip('\n').split(',')
    if len(f) < 12 or f[1] != '5' or not f[11].startswith('22'):
        continue
    rows[int(f[0])] = (bytes.fromhex(f[11].split(':')[0]), re.findall(r'(\d+)/([0-9A-F]+):(\d+):(\d+):([0-9A-F]+)', f[10]))
poses = {}
for frame, (_, entries) in sorted(rows.items()):
    prev = rows.get(frame - 2)
    if prev is None or prev[0][1] != 2 or len(entries) < 4:
        continue
    pose = prev[0][11]
    if pose not in poses:
        poses[pose] = (prev[0][3], prev[0][5], entries)
orb = []
for pose in (0x8F, 0x90, 0x91):
    y0, x0, entries = poses[pose]
    pix = [[0] * 32 for _ in range(32)]
    for _, p, sy, sx, col in sorted(entries, key=lambda e: -int(e[0])):   # sprite 0 on top
        rows, colour = layer(vram, base, int(p, 16)), int(col, 16) & 15
        for r in range(16):
            for c in range(16):
                if rows[r] & (0x8000 >> c):
                    py, px = int(sy) - (y0 - 16) + r, int(sx) - (x0 - 16) + c
                    if 0 <= py < 32 and 0 <= px < 32:
                        pix[py][px] = colour
    orb += tiles(pix, 4, 4)


def table(name, v):
    body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(v))
    return f'const u32 {name}[{len(v)}] = {{{body}\n}};\n'


(OUT / 'boss6_md.h').write_text(f"""/* Generated by tools/build_boss6_md.py from openMSX VRAM snapshots. */
#ifndef VK_BOSS6_MD_H
#define VK_BOSS6_MD_H
#include <genesis.h>
#define VK_BOSS6_TILE_COUNT {len(boss) // 8}
#define VK_ORB6_TILE_COUNT {len(orb) // 8}
extern const u32 vk_boss6_tiles[{len(boss)}];
extern const u32 vk_orb6_tiles[{len(orb)}];
#endif
""")
(OUT / 'boss6_md.c').write_text('/* Generated by tools/build_boss6_md.py from openMSX VRAM snapshots. */\n#include "boss6_md.h"\n'
                                + table('vk_boss6_tiles', boss) + table('vk_orb6_tiles', orb))
print('boss tiles', len(boss) // 8, 'orb tiles', len(orb) // 8, {hex(k): (v[0], v[1], len(v[2])) for k, v in poses.items()})
