#!/usr/bin/env python3
"""Sprites of the stage 8 objects, in the layout of the type 5 block (pattern N is tile N - 0x40, a cell is
four tiles). Patterns come from VRAM snapshots of openMSX runs (they are compressed in the ROM, 46F1); the
runs are not versioned, see research/stage8-enemies.md. Each cell is a sprite pose; the two layers (pattern N
in colour a, N + 4 in colour b, CC = OR) are composed in it. Cells (destination, source pattern, colours):
  40 48 50 58   object 08 (room 1), poses 71 to 74, colours 2 and 5
  44 4C 54 5C   statue 0A (rooms 6, 7), top and bottom, eyes colour 12 / 8
  60            fireball of the statue (D700 type 3), pattern F0 colour 8
  64 68 6C 70   object 0B facing left, poses 47 and 48 (top, bottom), colours 2 and 12
  74 78 7C 80   object 0B facing right, poses 49 and 4A
  84 88 8C 90 94  object 0C, poses 87, 88, 89, 8A, 8B, colours 2 and 1
  98 9C A0      bone of the object 0B (D700 type 4), poses 4B, 4C, 4D, colours 2 and 12
Usage: build_stage8_enemies_md.py RUN_R RUN_L
"""
import glob, sys
from pathlib import Path

runs = {'R': Path(sys.argv[1]), 'L': Path(sys.argv[2])}
cells = {}   # destination pattern -> 16 x 16 pixels


def snap(run, label):
    base = sorted(glob.glob(str(runs[run] / 'snaps' / f'*_{label}.vram')))[0][:-5]
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    return vram, (regs[6] & 0x3F) << 11


def layers(run, label, dest, *spec):
    vram, sprites = snap(run, label)
    pix = [[0] * 16 for _ in range(16)]
    for pattern, colour in spec:
        a = sprites + pattern * 8
        for y in range(16):
            row = (vram[a + y] << 8) | vram[a + 16 + y]
            for x in range(16):
                if row & (0x8000 >> x):
                    pix[y][x] |= colour
    cells[dest] = pix


for n, label in ((0x40, 'r1_4044'), (0x48, 'r1_484C'), (0x50, 'r1_5054'), (0x58, 'r1_585C')):
    layers('R', label, n, (n, 2), (n + 4, 5))
layers('L', 'r6_C0C4C8CC5054', 0x44, (0xC0, 2), (0xC4, 12))
layers('L', 'r6_C0C4C8CC5054', 0x4C, (0xC8, 2), (0xCC, 12))
layers('L', 'r6_C0C4C8CC5054', 0x54, (0xC0, 2), (0xC4, 8))
layers('L', 'r6_C0C4C8CC5054', 0x5C, (0xC8, 2), (0xCC, 8))
layers('L', 'r6_C0C44044F0C8CC', 0x60, (0xF0, 8))
for dest, run, label, top, bottom in ((0x64, 'R', 'r2_4044A4A0484C', 0x40, 0x48), (0x6C, 'R', 'r2_5054585CA4A0', 0x50, 0x58),
                                      (0x74, 'L', 'r3_6064686C', 0x60, 0x68), (0x7C, 'L', 'r3_7074787C', 0x70, 0x78)):
    layers(run, label, dest, (top, 2), (top + 4, 12))
    layers(run, label, dest + 4, (bottom, 2), (bottom + 4, 12))
for dest, run, label, n in ((0x84, 'L', 'r6_C0C4484CC8CC', 0x48), (0x88, 'L', 'r6_C0C44044F0C8CC', 0x40),
                            (0x8C, 'R', 'r5_5054', 0x50), (0x90, 'R', 'r5_6064', 0x60), (0x94, 'R', 'r5_585C', 0x58)):
    layers(run, label, dest, (n, 2), (n + 4, 1))
layers('R', 'r2_9490585C5054', 0x98, (0x90, 2), (0x94, 12))
layers('R', 'r2_50549C98585C', 0x9C, (0x98, 2), (0x9C, 12))
layers('R', 'r2_A4A0585C5054', 0xA0, (0xA0, 2), (0xA4, 12))

words = []
for pattern in range(0x40, 0xC0, 4):
    pix = cells.get(pattern, [[0] * 16 for _ in range(16)])
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage8_enemies_md.h').write_text(f"""/* Generated by tools/build_stage8_enemies_md.py. */
#ifndef VK_STAGE8_ENEMIES_MD_H
#define VK_STAGE8_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE8_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage8_enemy_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage8_enemies_md.c').write_text('/* Generated by tools/build_stage8_enemies_md.py. */\n#include "stage8_enemies_md.h"\n'
    f'const u32 vk_stage8_enemy_tiles[{len(words)}] = {{{body}\n}};\n')
for dest in sorted(cells):
    print(hex(dest), sum(1 for row in cells[dest] if any(row)), 'rows')
