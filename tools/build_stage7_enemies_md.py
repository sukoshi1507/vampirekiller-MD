#!/usr/bin/env python3
"""Sprites of the stage 7 objects, in the layout of the type 5 block (pattern N is tile N - 0x40, a cell is
four tiles). Patterns come from VRAM snapshots of openMSX runs (the game copies the patterns of the pose on
show into the sprite generator, so a snapshot is chosen by the patterns of its SAT); the runs are not
versioned, see research/stage7-enemies.md. Cells (destination pattern, source patterns, colours) :
  64..80   skeleton 0B, poses 47..4A : top (64 + 8k) and bottom (68 + 8k), layers N and N+4, colours 2 and 12
  84..94   flying creature 0C, poses 87, 88, 89, 8A, 8B : layers N and N+4, colours 2 and 1
  98 9C A0 bone (D700 type 4), poses 4B, 4C, 4D : layers N and N+4 (90, 98, A0), colours 2 and 12
  A4..B0   flea 0D, poses 67, 68, 6A, 6B : patterns A8, B0, C0, C8, colours 2 and 5
0B, 0C and the bone are the ROM objects of stage 8 and share its sprite code (enemies.c), so their cells sit where the
stage 8 block puts them; the flea takes A4..B0 as in the stage 9 block (fleaBase).
The two layers of a MSX sprite pair are ORed (CC bit), so a pixel set in both takes colour a | b.
Usage: build_stage7_enemies_md.py RUN... (directories holding snaps/*.vram and *.txt)"""
import glob, sys
from pathlib import Path

runs = [Path(a) for a in sys.argv[1:]]
cells = {}


def find(n, rooms):
    """A snapshot whose SAT held the patterns n and n + 4 (file name f<frame>_r<room>_<patterns>.vram)."""
    pair = f'{n:02X}{n + 4:02X}'
    pair2 = f'{n + 4:02X}{n:02X}'
    for run in runs:
        for f in sorted(glob.glob(str(run / 'snaps' / '*.vram'))):
            parts = Path(f).name[:-5].split('_')
            if len(parts) < 3 or parts[1][1:] not in rooms or len(parts[2]) % 4: continue
            keys = [parts[2][i:i + 4] for i in range(0, len(parts[2]), 4)]
            if pair in keys or pair2 in keys:
                return f[:-5]
    raise SystemExit(f'no snapshot for patterns {n:02X}/{n + 4:02X} in rooms {rooms}')


def layers(dest, n, rooms, c1, c2):
    base = find(n, rooms)
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    sprites = (regs[6] & 0x3F) << 11
    pix = [[0] * 16 for _ in range(16)]
    for pattern, colour in ((n, c1), (n + 4, c2)):
        a = sprites + pattern * 8
        for y in range(16):
            row = (vram[a + y] << 8) | vram[a + 16 + y]
            for x in range(16):
                if row & (0x8000 >> x):
                    pix[y][x] |= colour
    cells[dest] = pix


SK = ('3', '6')
for k in range(4):
    layers(0x64 + 8 * k, 0x40 + 16 * k, SK, 2, 12)
    layers(0x68 + 8 * k, 0x48 + 16 * k, SK, 2, 12)
for i, n in enumerate((0x48, 0x40, 0x50, 0x60, 0x58)):
    layers(0x84 + 4 * i, n, ('7', '8'), 2, 1)
for i, n in enumerate((0x90, 0x98, 0xA0)):
    layers(0x98 + 4 * i, n, ('3', '6', '4'), 2, 12)
for i, n in enumerate((0xA8, 0xB0, 0xC0, 0xC8)):
    layers(0xA4 + 4 * i, n, ('4', '1'), 2, 5)

words = []
for pattern in range(0x40, 0xC0, 4):
    pix = cells.get(pattern, [[0] * 16 for _ in range(16)])
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage7_enemies_md.h').write_text(f"""/* Generated by tools/build_stage7_enemies_md.py. */
#ifndef VK_STAGE7_ENEMIES_MD_H
#define VK_STAGE7_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE7_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage7_enemy_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage7_enemies_md.c').write_text('/* Generated by tools/build_stage7_enemies_md.py. */\n#include "stage7_enemies_md.h"\n'
    f'const u32 vk_stage7_enemy_tiles[{len(words)}] = {{{body}\n}};\n')
for dest in sorted(cells):
    print(hex(dest), sum(1 for row in cells[dest] if any(row)), 'rows')
