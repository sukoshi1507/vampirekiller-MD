#!/usr/bin/env python3
"""Vectors for tests/test_stage11.c : the eagle (object 0F, routine B1C3, init B193) and the flea it carries (object 23h, routine B248, init B212) of the
stage 11 rooms 2 to 4, run pass by pass by the original Z80 routines (5F1D creating the eagle, then 993B, 99B9 and 99E5 for each object in block order)
in the kosarev/z80 emulator on the maps of the stage 11, Simon moved by a scripted triangle wave. LD A,R (B216, B29E) is replaced by LD A,n so that the run
is reproducible (the port reads Enemies_s7R). A row is, for the eagle then the flea, (alive, +1 state, X, Y, +B pose, vx, vy, +6 mobile, +C, +11, +4 X fraction,
+2 Y fraction) after the pass. Usage: gen_stage11_vectors.py ROM OUT.h"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from castle_room_objects import make_machine, call
from probe import load_rom

PASSES = 260
# room, Y of the eagle (30h or 40h from the channel 9DE7), R, Simon X (low, high, step per pass), Simon Y
SCENARIOS = []
for room in (2, 3, 4):
    for ey in (0x30, 0x40):
        for r, lo, hi, step, sy in ((0, 20, 200, 2, 176), (5, 20, 190, 3, 176), (64, 100, 100, 0, 176), (3, 20, 60, 1, 176), (127, 20, 190, 5, 144),
                                    (2, 130, 190, 1, 112), (1, 20, 100, 4, 176)):
            SCENARIOS.append((room, ey, r, lo, hi, step, sy))


def build(data, room, R):
    data = bytearray(data)
    for addr in (0x7216, 0x729E):           # CPU B216 and B29E (bank 3 at A000: file 0x6000 + addr - 0xA000)
        pass
    for cpu in (0xB216, 0xB29E):
        off = 0x6000 + cpu - 0xA000
        assert data[off:off + 2] == b'\xED\x5F', hex(cpu)
        data[off:off + 2] = bytes((0x3E, R))      # LD A,n
    m = make_machine(bytes(data))
    mem = m.memory
    mem[0xD000] = 11; mem[0xD001] = room; mem[0xD002] = data[0x1E6A + 11]; mem[0xC41A] = 0
    call(m, 0x5A49); call(m, 0x5B1B); call(m, 0x4F83)
    for w in range(4):
        m.set_memory_block(0x4000 + w * 8192, bytes(data)[w * 8192:(w + 1) * 8192])
    mem[0xD012] = 0; mem[0xC420] = 0; mem[0xCE00] = 0; mem[0xCE03] = 0; mem[0xD010] = 0
    for a in range(0xD600, 0xD700, 4): mem[a] = 0xE0
    for k in range(7):
        for i in range(0x80): mem[0xC800 + 0x80 * k + i] = 0
    for k in range(8):
        for i in range(0x80): mem[0xD700 + 0x80 * k + i] = 0
    return m, bytes(data)


def snap(mem, b):
    t = mem[b]
    return (1 if t else 0, mem[b + 1], mem[b + 5], mem[b + 3], mem[b + 11], mem[b + 9] | mem[b + 10] << 8, mem[b + 7] | mem[b + 8] << 8,
            mem[b + 6], mem[b + 12], mem[b + 17], mem[b + 4], mem[b + 2])


def run(data, room, ey, R, lo, hi, step, sy):
    m, d = build(data, room, R)
    mem = m.memory
    mem[0xC427] = lo; mem[0xC425] = sy
    m.de = 0xE000 | ey; m.c = 0x0F
    call(m, 0x5F1D)                       # the channel 9DE7 : eagle at (E0, ey), its init B193 makes the flea
    assert mem[0xC800] == 0x0F and mem[0xC880] == 0x23, (hex(mem[0xC800]), hex(mem[0xC880]))
    table = 0x1F42 + 0  # 9942 in the bank 2 at 8000 : file 0x4000 + 0x1942
    rows = []
    span = max(hi - lo, 0)
    for p in range(PASSES):
        t = (p * step) % (2 * span) if span else 0
        mem[0xC427] = lo + (2 * span - t if t > span else t)
        alive = 0
        for k in range(7):
            b = 0xC800 + 0x80 * k
            typ = mem[b]
            if not typ: continue
            o = 0x4000 + 0x9942 - 0x8000 + 2 * (typ - 1)
            m.ix = b
            call(m, d[o] | d[o + 1] << 8)
            m.ix = b
            call(m, 0x99B9)
            m.ix = b
            call(m, 0x99E5)
        a, b2 = snap(mem, 0xC800), snap(mem, 0xC880)
        rows.append(a + b2)
        if not a[0] and not b2[0]: break
    return rows


def main():
    data = load_rom(Path(sys.argv[1]))
    out = ["/* Generated by tools/gen_stage11_vectors.py from the reference ROM routines (Z80 emulator). Do not edit. */",
           "typedef struct { int room, ey, r, lo, hi, step, sy, passes, first; } Stage11Vector;",
           "static const int stage11_rows[] = {"]
    vec, nrows = [], 0
    stat = dict(hover=0, drop=0, fall=0, walk=0, gone=0)
    for sc in SCENARIOS:
        rows = run(data, *sc)
        vec.append((sc, len(rows), nrows))
        prev = None
        for r in rows:
            out.append(" " + ",".join(str(v) for v in r) + ",")
            if prev:
                if prev[1] == 0 and r[1] == 1: stat['hover'] += 1
                if prev[13] == 0 and r[13] == 1: stat['drop'] += 1
                if prev[13] == 1 and r[13] == 2: stat['fall'] += 1
                if prev[13] in (2, 3) and r[13] == 3: stat['walk'] += 1
                if prev[0] and not r[0]: stat['gone'] += 1
            prev = r
            nrows += 1
    out.append("};")
    out.append("static const Stage11Vector stage11_vectors[] = {")
    for sc, n, first in vec:
        out.append(" {%d,%d,%d,%d,%d,%d,%d,%d,%d}," % (*sc, n, first))
    out.append("};")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(len(vec), 'scenarios', nrows, 'rows;', stat)


if __name__ == '__main__':
    main()
