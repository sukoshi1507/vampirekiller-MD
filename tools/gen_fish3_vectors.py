#!/usr/bin/env python3
"""Vectors for tests/test_fish3.c : the objects 03 and 21h of the stage 10 (init A2E0 or A2C7, routine A310, then 99B9 and 99E5), run pass by
pass by the original Z80 routines in the kosarev/z80 emulator on the maps of the stage 10, Simon moved by a scripted triangle wave. A row is
(+1 state, X, Y, pose +B, vx, vy, +10, +11, +12, alive, D700 type, D700 X, D700 Y) after the pass. Usage: gen_fish3_vectors.py ROM OUT.h"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from castle_room_objects import make_machine, call
from probe import load_rom

PASSES = 300
# type, room, X, Y, Simon X (low, high, step per pass), Simon Y
SCENARIOS = []
# Object 03 out of the water (rooms 1 to 5, the channel 9D52 creates it at Y C8h, X of the table 9D87).
for room in (1, 2, 3, 4, 5):
    for x, lo, hi, step, sy in ((96, 20, 230, 3, 144), (208, 20, 230, 2, 112), (48, 100, 100, 0, 144), (160, 20, 230, 5, 80), (208, 20, 60, 1, 144)):
        SCENARIOS.append((3, room, x, 0xC8, lo, hi, step, sy))
# Object 21h of the fixed list (rooms 6 to 8), Simon moved at its height and away from it.
for room, x, y in ((6, 48, 176), (6, 192, 176), (7, 128, 176), (8, 48, 176), (8, 208, 176)):
    for lo, hi, step, sy in ((20, 230, 3, 176), (20, 230, 3, 100), (20, 230, 2, 170), (100, 100, 0, 176)):
        SCENARIOS.append((0x21, room, x, y, lo, hi, step, sy))


def build(data, stage, room):
    m = make_machine(bytes(data))
    mem = m.memory
    mem[0xD000] = stage; mem[0xD001] = room; mem[0xD002] = data[0x1E6A + stage]; mem[0xC41A] = 0
    call(m, 0x5A49); call(m, 0x5B1B); call(m, 0x4F83)
    for w in range(4):
        m.set_memory_block(0x4000 + w * 8192, bytes(data)[w * 8192:(w + 1) * 8192])
    mem[0xD012] = 0; mem[0xC420] = 0; mem[0xCE00] = 0; mem[0xCE03] = 0
    for a in range(0xD600, 0xD700, 4): mem[a] = 0xE0
    for a in range(0xD638, 0xD680, 4): mem[a] = 0xE0
    for k in range(7):
        for i in range(0x80): mem[0xC800 + 0x80 * k + i] = 0
    for k in range(8):
        for i in range(0x80): mem[0xD700 + 0x80 * k + i] = 0
    return m


def run(data, typ, room, x, y, lo, hi, step, sy):
    m = build(data, 10, room)
    mem = m.memory
    b = 0xC800
    mem[0xC427] = lo; mem[0xC425] = sy
    mem[b] = typ; mem[b + 3] = y; mem[b + 5] = x
    mem[b + 0x7E] = 1; mem[b + 0x7F] = 1; mem[b + 13] = data[0x20E1 + typ]
    m.ix = b
    call(m, data[0x1FCC + 2 * (typ - 1)] | data[0x1FCD + 2 * (typ - 1)] << 8)
    rows = []
    span = max(hi - lo, 0)
    for p in range(PASSES):
        t = (p * step) % (2 * span) if span else 0
        mem[0xC427] = lo + (2 * span - t if t > span else t)
        if mem[b] not in (3, 0x21): break
        m.ix = b
        call(m, 0xA310)
        call(m, 0x99B9); call(m, 0x99E5)
        rows.append((mem[b + 1], mem[b + 5], mem[b + 3], mem[b + 11], mem[b + 9] | mem[b + 10] << 8, mem[b + 7] | mem[b + 8] << 8,
                     mem[b + 16], mem[b + 17], mem[b + 18], 1 if mem[b] in (3, 0x21) else 0, mem[0xD700], mem[0xD705], mem[0xD703]))
        if mem[b] not in (3, 0x21): break
    return rows


def main():
    data = load_rom(Path(sys.argv[1]))
    out = ["/* Generated by tools/gen_fish3_vectors.py from the reference ROM routines (Z80 emulator). Do not edit. */",
           "typedef struct { int type, room, x, y, lo, hi, step, sy, passes, first; } Fish3Vector;",
           "static const int fish3_rows[] = {"]
    vec, nrows = [], 0
    stat = dict(fire=0, dive=0, edge=0, walk=0, trig=0)
    for sc in SCENARIOS:
        rows = run(data, *sc)
        vec.append((sc, len(rows), nrows))
        prev = None
        for r in rows:
            out.append(" %d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d," % r)
            if r[10] and not (prev and prev[10]): stat['fire'] += 1
            if prev and prev[0] == 1 and r[0] == 0: stat['edge'] += 1
            if prev and prev[9] and not r[9]: stat['dive'] += 1
            if prev and prev[0] == 2 and r[0] == 1: stat['walk'] += 1
            prev = r
            nrows += 1
    out.append("};")
    out.append("static const Fish3Vector fish3_vectors[] = {")
    for sc, n, first in vec:
        out.append(" {%d,%d,%d,%d,%d,%d,%d,%d,%d,%d}," % (*sc[:8], n, first))
    out.append("};")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(len(vec), 'scenarios', nrows, 'rows;', stat)


if __name__ == '__main__':
    main()
