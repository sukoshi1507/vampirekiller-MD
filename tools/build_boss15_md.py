#!/usr/bin/env python3
"""Run ROM stage15 graphics loader5780 and sprite writer6445; emit body/projectile cells."""
import argparse
from probe import load_rom,reference_rom,ROOT
from build_boss12_md import BossGraphics

def generate():
 h=BossGraphics(load_rom(reference_rom()));m=h.cpu;mem=m.memory
 mem[0xD000]=15;mem[0xD001]=9;mem[0xD002]=4;mem[0xCE00]=5;mem[0xF0F1:0xF0F4]=bytes([1,2,3])
 h.call(0x5768);h.call(0x5780)
 assert any(h.vram[0xFF80:0xFFA0]), "common initial pose3 must be loaded"
 for a in range(0xD600,0xD700,4):mem[a]=0xE0
 h.call(0xB6AB);cells=[];words=[]
 for pose in list(range(0x7C,0x81))+[3]:
  a=0xC800 if pose==0x7C else 0xD700;m.ix=a;mem[a+11]=pose;h.call(0x6445)
  for k in range(0,mem[a+32],2):
   b=a+34+5*k;assert mem[b:b+2]==mem[b+5:b+7];assert mem[b+7]==mem[b+2]+(0 if pose==3 else 4)
   colors=(mem[b+3],mem[b+8]);assert colors==((2,0x45) if pose==0x7C else (0x42,5))
   # For D700 the slots run backwards: the plain05 layer has lower SAT index than CC42.
   if pose!=0x7C:assert mem[b-1]>mem[b+4]
   dy=(mem[b]-mem[a+3]+128)%256-128;dx=(mem[b+1]-mem[a+5]+128)%256-128
   pattern=mem[b+2];cells.append((dy,dx,pattern,len(words)//8))
   pixels=[[0]*16 for _ in range(16)]
   for pat,col in [(pattern,colors[0]&15),(pattern+(0 if pose==3 else 4),colors[1]&15)]:
    address=0xF800+8*pat
    for y in range(16):
     bits=256*h.vram[address+y]+h.vram[address+y+16]
     for x in range(16):
      if bits&(0x8000>>x):pixels[y][x]|=col
   for c in range(2):
    for r in range(2):
     for y in range(8):
      value=0
      for x in range(8):value=value*16+pixels[8*r+y][8*c+x]
      words.append(value)
 assert len(cells)==11 and len(words)==352
 poses='''/* Generated by tools/build_boss15_md.py via5780/6445. */
#ifndef VK_BOSS15_POSES_H
#define VK_BOSS15_POSES_H
typedef struct { signed char dy,dx; unsigned char pattern,tile; } VKBoss15Cell;
static const VKBoss15Cell vk_boss15_cells[11] = {
'''+''.join(' {'+','.join(map(str,c))+'},\n' for c in cells)+'};\n#endif\n'
 header='''/* Generated by tools/build_boss15_md.py. */
#ifndef VK_BOSS15_MD_H
#define VK_BOSS15_MD_H
#include <genesis.h>
#define VK_BOSS15_TILE_COUNT 44
extern const u32 vk_boss15_tiles[352];
#endif
'''
 data='/* Generated by tools/build_boss15_md.py. */\n#include "boss15_md.h"\nconst u32 vk_boss15_tiles[352] = {\n'+''.join(' '+','.join(f'0x{x:08X}' for x in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'
 return {'boss15_poses.h':poses,'boss15_md.h':header,'boss15_md.c':data}

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
 for name,text in generate().items():
  dest=ROOT/'sgdk/src/generated'/name
  if args.check:assert dest.read_text()==text,f'{name}: regenerate'
  else:dest.write_text(text)
 print('boss15: body + CC projectile,11 cells,44 tiles', 'CHECK PASS' if args.check else 'generated')
if __name__=='__main__':main()
