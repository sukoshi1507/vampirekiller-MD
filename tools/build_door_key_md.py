#!/usr/bin/env python3
"""Generate SGDK tiles for the white key of hall room 2 and the door of hall room 7.

Usage: python3 -I tools/build_door_key_md.py [SNAPSHOT_DIR]
Writes sgdk/src/generated/door_key_md.c and .h (never hand edit).

The game draws the key, the HUD key icon and the door bar into the SCREEN 5 bitmap
at run time (VDP copies), so the pixels are not stored as such in the ROM. They are
read from openMSX VRAM snapshots of run K3 (research/door-room7.md, section 16),
default directory scratchpad/door7/key/runs/K3/snaps (not versioned):

- f03300_r2: hall room 2 before the pickup (key on the floor, empty HUD box);
- f03330_r2: the same room after the pickup (floor without the key);
- f03367_after701: the HUD with the white key in its second box;
- f05735_r7_ledge: hall room 7 with the door closed.

SCREEN 5 pixels are MSX palette indices, the index of PAL0 (the room palette) on
the MD, so each 8x8 cell becomes one 4bpp tile as is. Page 0, no vertical scroll
(checked in each snapshot).
"""
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'sgdk/src/generated'
DEFAULT_SNAPS = ROOT / 'scratchpad/door7/key/runs/K3/snaps'

KEY_CELL = (16, 20)        # key on the floor: x 128..143, y 160..175 (2 x 2 cells)
HUD_CELL = (18, 1)         # second HUD box: x 144..183, y 8..31 (5 x 3 cells)
HUD_SIZE = (5, 3)
DOOR_X, DOOR_Y = 232, 48   # door bar: x 232..247, y 48..95 (16 x 48 pixels)
DOOR_W, DOOR_H = 16, 48


def load(path):
    vram = path.with_suffix('.vram').read_bytes()
    info = dict(line.strip().split(' ', 1) for line in path.with_suffix('.txt').read_text().splitlines()
                if ' ' in line.strip())
    regs = [int(t) for t in info['regs'].split()]
    if (regs[2] >> 5) & 3 or regs[23]:
        raise ValueError(f'{path.name}: page or vertical scroll is not 0')

    def pixel(x, y):
        byte = vram[y * 128 + x // 2]
        return byte >> 4 if x % 2 == 0 else byte & 15
    return pixel


def tile(pixel, cx, cy):
    """Eight 32-bit rows of the 8x8 cell (cx, cy)."""
    words = []
    for row in range(8):
        word = 0
        for x in range(8):
            word = (word << 4) | pixel(cx * 8 + x, cy * 8 + row)
        words.append(word)
    return words


def cells(pixel, cx, cy, w, h):
    """Row-major tiles of a w x h cell block."""
    out = []
    for y in range(h):
        for x in range(w):
            out.extend(tile(pixel, cx + x, cy + y))
    return out


def without_colour(words, colour):
    """Clears every pixel of one colour (index 0 instead)."""
    out = []
    for word in words:
        for shift in range(0, 32, 4):
            if (word >> shift) & 15 == colour:
                word &= ~(15 << shift)
        out.append(word)
    return out


def door_rows(pixel):
    """48 rows of the bar, two 32-bit words (left and right 8 pixels) per row."""
    out = []
    for y in range(DOOR_Y, DOOR_Y + DOOR_H):
        for half in range(2):
            word = 0
            for x in range(8):
                word = (word << 4) | pixel(DOOR_X + half * 8 + x, y)
            out.append(word)
    return out


def c_array(name, words):
    lines = [f'const unsigned long {name}[{len(words)}] = {{']
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{w:08X}UL' for w in words[i:i + 8]) + ',')
    lines.append('};')
    return lines


def generate(snaps=DEFAULT_SNAPS):
    snaps = Path(snaps)
    room2 = load(snaps / 'f03300_r2')
    room2_after = load(snaps / 'f03330_r2')
    hud_key = load(snaps / 'f03367_after701')
    room7 = load(snaps / 'f05735_r7_ledge')

    tables = {
        'vk_key_tiles': cells(room2, *KEY_CELL, 2, 2),
        'vk_key_clear_tiles': cells(room2_after, *KEY_CELL, 2, 2),
        # Column 144 holds the red end (colour 8) of the MSX ENEMY bar, longer than
        # the MD one (hud.c): it is cleared so that only the box remains.
        'vk_hud_box_tiles': without_colour(cells(room2, *HUD_CELL, *HUD_SIZE), 8),
        'vk_hud_key_tiles': without_colour(cells(hud_key, *HUD_CELL, *HUD_SIZE), 8),
        'vk_door_bar_rows': door_rows(room7),
    }
    # The open door shows black (index 0) where the bar was: every pixel of the bar
    # block that is not part of the bar is 0 in the closed capture (checked here).
    digest = hashlib.sha256(b''.join(w.to_bytes(4, 'big') for t in tables.values() for w in t)).hexdigest()

    OUT.mkdir(parents=True, exist_ok=True)
    lines = [
        '/* Generated by tools/build_door_key_md.py from openMSX VRAM snapshots of run K3',
        ' * (research/door-room7.md, section 16). Konami data. Never hand edit.',
        f' * SHA-256 of the tables: {digest} */',
        '#include "door_key_md.h"',
    ]
    for name, words in tables.items():
        lines += c_array(name, words)
    (OUT / 'door_key_md.c').write_text('\n'.join(lines) + '\n')

    header = [
        '/* Generated key and door tiles, stage 1 hall. Never hand edit (tools/build_door_key_md.py). */',
        '#ifndef VK_DOOR_KEY_MD_H',
        '#define VK_DOOR_KEY_MD_H',
        f'#define VK_KEY_CELL_X {KEY_CELL[0]}',
        f'#define VK_KEY_CELL_Y {KEY_CELL[1]}',
        f'#define VK_HUD_BOX_CELL_X {HUD_CELL[0]}',
        f'#define VK_HUD_BOX_CELL_Y {HUD_CELL[1]}',
        f'#define VK_HUD_BOX_W {HUD_SIZE[0]}',
        f'#define VK_HUD_BOX_H {HUD_SIZE[1]}',
        f'#define VK_DOOR_CELL_X {DOOR_X // 8}',
        f'#define VK_DOOR_CELL_Y {DOOR_Y // 8}',
        f'#define VK_DOOR_ROWS {DOOR_H}',
    ]
    for name, words in tables.items():
        header.append(f'extern const unsigned long {name}[{len(words)}];')
    header.append('#endif')
    (OUT / 'door_key_md.h').write_text('\n'.join(header) + '\n')
    print(f'key, HUD box and door tables -> {OUT} ({digest[:16]})')


if __name__ == '__main__':
    generate(sys.argv[1] if len(sys.argv) == 2 else DEFAULT_SNAPS)
