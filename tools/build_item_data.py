#!/usr/bin/env python3
"""Execute projectile box selector8264 and room object decoder5B1B for item rules."""
import argparse
from probe import ROOT,load_rom,reference_rom
from verify_trade_trace import TradeHarness
from castle_room_objects import decode_room
from decode_room_links import decode

def generate():
 rom=load_rom(reference_rom());h=TradeHarness(rom);boxes=[(0,0)]
 h.stop=0x864B;h.cpu.set_breakpoint(h.stop)
 for kind in range(1,13):
  h.cpu.memory[0xD700]=kind;h.cpu.ix=0xD700;h.call(0x8264);boxes.append((h.cpu.l,h.cpu.h))
 h.stop=None;h.call(0x63C5);h.cpu.c=30;h.cpu.de=0;h.call(0x5F1D);death=list(h.cpu.memory[0xC800:0xC820])
 samples=[]
 for seed in (0xA5,0x5A):
  h.call(0x63C5);h.cpu.memory[0xC800:0xC820]=bytes([0]+[seed]*31);h.cpu.c=30;h.cpu.de=0;h.call(0x5F1D);samples.append(list(h.cpu.memory[0xC800:0xC820]))
 death_mask=[int(a==b) for a,b in zip(*samples)]
 counts=[len(s['rooms']) for s in decode(rom)];blocks=[]
 for stage in range(19):
  row=[]
  for room in range(12):
   slots=[(0,0,0,0)]*8
   if room<counts[stage]:
    for obj in decode_room(rom,stage,room)['candles']:
     b=bytes.fromhex(obj['raw']);i=(int(obj['slot'],16)-0xC470)//16
     if b[4]>=2:slots[i]=(b[2],b[1],b[4],b[9])
   row.append(slots)
  blocks.append(row)
 header='''/* Generated by tools/build_item_data.py; executed8264/5B1B. */
#ifndef VK_ITEM_DATA_H
#define VK_ITEM_DATA_H
#include "../player.h"
typedef struct { VKByte x,y,mode,content; } VKItemBlock;
extern const VKByte vk_item_projectile_box[13][2];
extern const VKItemBlock vk_item_blocks[19][12][8];
#endif
'''
 header=header.replace('#endif','static const VKByte vk_item_death_prefix[32]={'+','.join(map(str,death))+'};\nstatic const VKByte vk_item_death_mask[32]={'+','.join(map(str,death_mask))+'};\n#endif')
 header=header.replace('extern const VKByte vk_item_projectile_box[13][2];','static const VKByte vk_item_shield_boxes[13][2]={'+','.join('{'+','.join(map(str,p))+'}' for p in boxes)+'};')
 data='/* Generated by tools/build_item_data.py. Included once by item_effects.c. */\nconst VKByte vk_item_projectile_box[13][2]={'+','.join('{'+','.join(map(str,p))+'}' for p in boxes)+'};\n'
 data+='const VKItemBlock vk_item_blocks[19][12][8]={\n'+''.join(' {'+','.join('{'+','.join('{'+','.join(map(str,p))+'}' for p in slots)+'}' for slots in row)+'},\n' for row in blocks)+'};\n'
 return {'item_data.h':header,'item_data.inc':data}

def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for name,text in generate().items():
  p=ROOT/'sgdk/src/generated'/name
  if a.check:assert p.read_text()==text,name
  else:p.write_text(text)
 print('Item data:12 projectile box selections;19 stages of hidden blocks', 'CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
