#!/usr/bin/env python3
"""Executed5F1D constructors1E/24/26: write masks distinguish retained IX bytes."""
import argparse
from probe import ROOT,load_rom,reference_rom
from verify_item_trace import setup
from build_boss12_md import BossGraphics

def generate():
 rom=load_rom(reference_rom());rows=[];masks=[]
 for kind in (36,38,30):
  samples=[]
  for fill in (0xA5,0x5A):
   h=setup(rom,12,0);h.call(0x63C5);m=h.cpu.memory;m[0xC800:0xC820]=bytes([0]+[fill]*31)
   h.cpu.c=kind;h.cpu.de=0;h.call(0x5F1D);samples.append(list(m[0xC800:0xC820]))
  rows.append(samples[0]);masks.append([int(a==b) for a,b in zip(*samples)])
 return '/* Generated by build_loot_data.py via executed5F1D. */\nstatic const unsigned char loot_init[3][32]={'+','.join('{'+','.join(map(str,r))+'}' for r in rows)+'};\nstatic const unsigned char loot_write[3][32]={'+','.join('{'+','.join(map(str,r))+'}' for r in masks)+'};\n'
def graphics():
 rom=load_rom(reference_rom());reference=None
 for stage in range(19):
  h=BossGraphics(rom);h.cpu.memory[0xD000]=stage;h.cpu.memory[0xD002]=rom[0x1E6A+stage];h.cpu.memory[0xF0F1:0xF0F4]=bytes((1,2,3));h.call(0x5768);h.call(0x5780)
  patterns=bytes(h.vram[0xFF40:0xFF80]) # E8/EC,32 bytes each
  if reference is None:reference=patterns
  else:assert patterns==reference,(stage,'loot bitmaps')
 words=[]
 for offset,colour in ((0,8),(32,8),(32,1),(32,14),(0,7)):
  pix=[[colour if ((reference[offset+y]<<8)|reference[offset+y+16])&(0x8000>>x) else 0 for x in range(16)] for y in range(16)]
  for c in range(2):
   for r in range(2):
    for y in range(8):words.append(sum(pix[8*r+y][8*c+x]<<(28-4*x) for x in range(8)))
 return {'loot_md.h':'/* Generated by build_loot_data.py. */\n#ifndef VK_LOOT_MD_H\n#define VK_LOOT_MD_H\n#include <genesis.h>\n#define VK_LOOT_TILE_COUNT 20\nextern const u32 vk_loot_tiles[160];\n#endif\n','loot_md.c':'/* Generated by build_loot_data.py: E8/EC common19-stage bitmaps. */\n#include "loot_md.h"\nconst u32 vk_loot_tiles[160]={\n'+''.join(','.join('0x%08X'%v for v in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();t=generate();f=ROOT/'sgdk/src/generated/loot_data.inc'
 outputs=graphics();outputs['loot_data.inc']=t
 for n,data in outputs.items():
  f=ROOT/'sgdk/src/generated'/n
  if a.check:assert f.read_text()==data,n
  else:f.write_text(data)
 print('Loot1E/24/26 executed constructor masks','CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
