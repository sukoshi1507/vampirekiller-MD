#!/usr/bin/env python3
"""Sprites of the stage 10 objects, in the layout of the type 5 block (pattern N is tile N - 0x40, a cell is four tiles).
Patterns come from VRAM snapshots of openMSX runs (they are compressed in the ROM); the runs are not versioned, see
research/stage10-enemies.md. Each cell is a sprite pose; the two layers (pattern N in colour 2, N + 4 in colour 5 with the CC bit = OR)
are composed in it. The MSX patterns are moved to a compact layout (destination cell <- source pattern):
  40 <- 80  top of the fishman (object 03 / 21h, routine A310) facing left, poses 0F and 10
  44 <- 88  bottom, pose 0F            48 <- 90  bottom, pose 10
  4C <- 98  top, pose 11 (fire)        50 <- A0  bottom, pose 11
  54 <- A8  top facing right, poses 12 and 13
  58 <- B0  bottom, pose 12            5C <- B8  bottom, pose 13
  60 <- F0  fireball (D700 type 1, A08E[2]), colour 8
  64 <- C0  top, pose 14 (fire, right) 68 <- C8  bottom, pose 14
  90 <- D0  splash drop (object 20h), colour 0Bh without CC
The moving platform (D8, DC) is stage10_platform_md.c (cell 6C of this block).
The bat of the room 0 (object 04, routine B0F8) is another image than the bat of the stage 2: vk_stage10_bat_tiles, in the layout of vk_enemy4_tiles (slot
(N - 0x48) / 4, one layer per cell: N colour 2, N + 4 colour 4), the left-facing patterns 48 to 5C from the snapshots, the right-facing ones (60 to 74) their mirrors
(checked on the stage 2 table: the right cells are the exact mirrors of the left ones).
Usage: build_stage10_enemies_md.py RUN_R  (the snapshots of the trace R, scratchpad/stage10/out/R2/snaps, research/stage10-enemies.md)
"""
import glob, sys
from pathlib import Path

run = Path(sys.argv[1])
cells = {}


def snap_for(n):
    """A snapshot where the pattern pair (n, n + 4) is in the SAT (the name lists the patterns)."""
    pair = f'{n:02X}{n + 4:02X}'
    found = [f for f in sorted(glob.glob(str(run / 'snaps' / '*_r*_*.vram'))) if pair in Path(f).name.split('_', 2)[2]]
    return found[0][:-5]


def layers(dest, src, *colours):
    base = snap_for(src) if len(colours) == 2 else sorted(glob.glob(str(run / 'snaps' / f'*_{src:02X}*.vram')))[0][:-5]
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    sprites = (regs[6] & 0x3F) << 11
    pix = [[0] * 16 for _ in range(16)]
    for k, colour in enumerate(colours):
        a = sprites + (src + 4 * k) * 8
        for y in range(16):
            row = (vram[a + y] << 8) | vram[a + 16 + y]
            for x in range(16):
                if row & (0x8000 >> x):
                    pix[y][x] |= colour
    cells[dest] = pix


for dest, src in ((0x40, 0x80), (0x44, 0x88), (0x48, 0x90), (0x4C, 0x98), (0x50, 0xA0), (0x54, 0xA8), (0x58, 0xB0), (0x5C, 0xB8),
                  (0x64, 0xC0), (0x68, 0xC8)):
    layers(dest, src, 2, 5)
layers(0x60, 0xF0, 8)
layers(0x90, 0xD0, 11)

words = []
for pattern in range(0x40, 0xC0, 4):
    pix = cells.get(pattern, [[0] * 16 for _ in range(16)])
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
def layer_pix(base, pattern, colour):
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    sprites = (regs[6] & 0x3F) << 11
    pix = [[0] * 16 for _ in range(16)]
    a = sprites + pattern * 8
    for y in range(16):
        row = (vram[a + y] << 8) | vram[a + 16 + y]
        for x in range(16):
            if row & (0x8000 >> x):
                pix[y][x] = colour
    return pix


def cell_words(pix):
    out = []
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                out.append(v)
    return out


bat = {}
for n in (0x48, 0x50, 0x58):
    base = snap_for(n)
    slot = (n - 0x48) // 4
    bat[slot] = layer_pix(base, n, 2)
    bat[slot + 1] = layer_pix(base, n + 4, 4)
    bat[slot + 6] = [row[::-1] for row in bat[slot]]
    bat[slot + 7] = [row[::-1] for row in bat[slot + 1]]
batwords = []
for slot in range(12):
    batwords += cell_words(bat.get(slot, [[0] * 16 for _ in range(16)]))
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage10_enemies_md.h').write_text(f"""/* Generated by tools/build_stage10_enemies_md.py. */
#ifndef VK_STAGE10_ENEMIES_MD_H
#define VK_STAGE10_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE10_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage10_enemy_tiles[{len(words)}];
extern const u32 vk_stage10_bat_tiles[{len(batwords)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage10_enemies_md.c').write_text('/* Generated by tools/build_stage10_enemies_md.py. */\n#include "stage10_enemies_md.h"\n'
    f'const u32 vk_stage10_enemy_tiles[{len(words)}] = {{{body}\n}};\n'
    + 'const u32 vk_stage10_bat_tiles[%d] = {%s\n};\n' % (len(batwords), ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(batwords))))
print(len(words) // 8, 'tiles')
for dest in sorted(cells):
    print(f'cell {dest:02X}')
    for r in cells[dest]:
        print(''.join(f'{v:X}' for v in r))
