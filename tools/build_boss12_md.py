#!/usr/bin/env python3
"""Execute stage12 graphics loader 5780 and sprite writer 6445; emit MD cells and layouts."""
import argparse
from pathlib import Path
from probe import load_rom,reference_rom,ROOT
from intro_harness import IntroHarness
from extract_enemy_sprites import mirror_layer

class BossGraphics(IntroHarness):
    def input(self,port):
        if port&255==0x98:
            value=self.vram[self.address&0x1FFFF]
            self.address=(self.address+1)&0x1FFFF
            return value
        return super().input(port)

def generate():
    h=BossGraphics(load_rom(reference_rom()));m=h.cpu;mem=m.memory
    mem[0xD000]=12;mem[0xD001]=6;mem[0xD002]=3;mem[0xCE00]=4
    mem[0xF0F1:0xF0F4]=bytes((1,2,3));h.call(0x5780)
    patterns=list(range(0x40,0x88,8))+list(range(0xA8,0xD8,8))
    # The real loader mirrors the rider. Verify the VDP read adapter preserves that operation.
    for n in (0xA8,0xB0,0xB8):
        a=0xF800+n*8;b=0xF800+(n+24)*8
        assert bytes(h.vram[b:b+64])==mirror_layer(h.vram[a:a+32])+mirror_layer(h.vram[a+32:a+64])
    words=[]
    for pattern in patterns:
        pixels=[[0]*16 for _ in range(16)]
        for n,color in ((pattern,2),(pattern+4,5)):
            a=0xF800+n*8
            for y in range(16):
                bits=h.vram[a+y]*256+h.vram[a+y+16]
                for x in range(16):
                    if bits&(0x8000>>x):pixels[y][x]|=color
        for c in range(2):
            for r in range(2):
                for y in range(8):
                    value=0
                    for x in range(8):value=value*16+pixels[8*r+y][8*c+x]
                    words.append(value)
    for a in range(0xD600,0xD700,4):mem[a]=0xE0
    h.call(0xB6AB)
    layouts=[]
    for pose in list(range(0x79,0x7C))+list(range(0x67,0x6D)):
        a=0xC800 if pose>=0x79 else 0xC880;m.ix=a;mem[a+11]=pose;h.call(0x6445)
        cells=[]
        for k in range(0,mem[a+32],2):
            b=a+34+5*k
            assert mem[b:b+2]==mem[b+5:b+7]
            assert mem[b+7]==mem[b+2]+4
            assert (mem[b+3],mem[b+8])==(2,0x45)
            dy=(mem[b]-mem[a+3]+128)%256-128;dx=(mem[b+1]-mem[a+5]+128)%256-128
            cells.append((dy,dx,mem[b+2],4*patterns.index(mem[b+2])))
        layouts.append((pose,cells))
    header='''/* Generated by tools/build_boss12_md.py via original 5780/6445. */
#ifndef VK_BOSS12_POSES_H
#define VK_BOSS12_POSES_H
typedef struct { signed char dy,dx; unsigned char pattern,tile; } VKBoss12Cell;
typedef struct { unsigned char pose,count; VKBoss12Cell cell[3]; } VKBoss12Pose;
static const VKBoss12Pose vk_boss12_poses[9] = {
'''
    for pose,cells in layouts:
        header+=' {'+str(pose)+','+str(len(cells))+',{'+','.join('{'+','.join(map(str,c))+'}' for c in cells)+'}},\n'
    header+='};\n#endif\n'
    hmd='''/* Generated by tools/build_boss12_md.py: 5780 executed with VDP VRAM reads. */
#ifndef VK_BOSS12_MD_H
#define VK_BOSS12_MD_H
#include <genesis.h>
#define VK_BOSS12_TILE_COUNT 60
#define VK_BOSS12_SHOT_TILE 60
extern const u32 vk_boss12_tiles[480];
#endif
'''
    data='/* Generated by tools/build_boss12_md.py. */\n#include "boss12_md.h"\nconst u32 vk_boss12_tiles[480] = {\n'
    for i in range(0,len(words),8):data+=' '+','.join(f'0x{x:08X}' for x in words[i:i+8])+',\n'
    data+='};\n'
    return {'boss12_poses.h':header,'boss12_md.h':hmd,'boss12_md.c':data}

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for name,text in generate().items():
        path=ROOT/'sgdk/src/generated'/name
        if args.check:assert path.read_text()==text,f'{name}: regenerate with tools/build_boss12_md.py'
        else:path.write_text(text)
    print('boss12: 5780/6445 graphics, mirrored rider, 9 poses and 60 MD tiles', 'CHECK PASS' if args.check else 'generated')
if __name__=='__main__':main()
