#!/usr/bin/env python3
"""Writes tests/stage9_boss_trace.inc and tests/stage9_enemy_trace.inc: real transitions of the openMSX traces of stage 9 (research/stage9-enemies.md and
research/stage9-boss.md), replayed by tests/test_stage9.c and tests/test_stage9_enemies.c. A transition is the object block (32 bytes, hex) of one sample,
the next different sample, and Simon's place of that image. Per kind, the first transitions of each (state, next state,
pose change, ...) key are kept, so every branch of the routines is covered.

Usage: gen_stage9_trace.py RUN_R RUN_B   (directories holding tr_boss.txt, tr_shot.txt, tr_hop.txt, tr_bone.txt, made by
the extraction of sat_s2.csv: scratchpad/stage8/extract.py CSV objs|proj TYPE OUT)
"""
import collections, sys
from pathlib import Path


def pick(files, key, per):
    seen, out = collections.Counter(), []
    for f in files:
        for line in open(f):
            p = line.split()
            if len(p) < 9:
                continue
            room, sx, sy, frame, slot, a, b, ax, ay = p[:9]
            if (ax, ay) != (sx, sy):
                continue                      # Simon moved between the sample and the poke of the plan: skip
            k = key(a, b)
            if seen[k] >= per:
                continue
            seen[k] += 1
            out.append((int(room), int(sx), int(sy), a, b))
    return out


def case(r):
    return '%d, %d, %d, "%s", "%s"' % r


runs = [Path(a) for a in sys.argv[1:3]]
walk = pick([r / 'tr_boss.txt' for r in runs], lambda a, b: (a[2:4], b[2:4], a[22:24] != b[22:24], a[32:34] != b[32:34]), 2)
shot = pick([r / 'tr_shot.txt' for r in runs], lambda a, b: (int(a[6:8], 16) // 8, int(a[10:12], 16) // 32), 1)
hop = pick([runs[0] / 'tr_hop.txt'], lambda a, b: (a[2:4], b[2:4], a[22:24] != b[22:24]), 3)
bone = pick([runs[0] / 'tr_bone.txt'], lambda a, b: (a[2:4], b[2:4]), 6)
tests = Path(__file__).resolve().parents[1] / 'tests'
for fname, what, sets in (('stage9_boss_trace.inc', 'the boss walkers and their fireballs', (('kWalk', walk), ('kShot', shot))),
                          ('stage9_enemy_trace.inc', 'the hopper 0B and its bone on the stage 9 maps', (('kHop9', hop), ('kBone9', bone)))):
    text = f'/* Generated by tools/gen_stage9_trace.py from openMSX traces of stage 9, {what}: room, Simon X, Simon Y, object block before and after one pass. */\n'
    for name, rows in sets:
        text += f'static const StepCase {name}[{len(rows)}] = {{\n' + ''.join('    {%s},\n' % case(r) for r in rows) + '};\n'
    (tests / fname).write_text(text)
print({n: len(r) for n, r in (('walker', walk), ('shot', shot), ('hopper', hop), ('bone', bone))})
