#!/usr/bin/env python3
"""Vectors for tests/test_stage7.c : the stage 7 objects 0B, 0C, 0D and the bone (D700 type 4), run pass by pass
by the original Z80 routines (993B, 99B9, 99E5 and the D700 loop 9E31) in the kosarev/z80 emulator, with Simon
moved by a scripted triangle wave. LD A,R (B216, B29E, B4AD) is replaced by LD A,n so that the run is reproducible
(the port reads Enemies_s7R). Usage: gen_stage7_vectors.py ROM OUT.h"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from castle_room_objects import make_machine, call
from probe import load_rom

PASSES = 260
# room, object index in the fixed list, type, R, Simon X (low, high, step per pass), Simon Y
SCENARIOS = [
    (2, 0x0B, 144, 176, 0, 232, 232, 0, 192), (2, 0x0B, 144, 176, 1, 20, 220, 3, 176),
    (3, 0x0B, 176, 192, 0, 40, 40, 0, 192), (3, 0x0B, 176, 192, 1, 20, 230, 2, 192),
    (4, 0x0B, 208, 192, 1, 10, 200, 5, 176), (5, 0x0B, 48, 144, 0, 100, 240, 1, 176),
    (6, 0x0B, 144, 176, 1, 30, 250, 4, 176), (4, 0x0B, 208, 192, 3, 232, 232, 0, 176),
    (1, 0x0D, 80, 144, 0, 232, 232, 0, 176), (1, 0x0D, 160, 144, 1, 20, 230, 2, 176),
    (4, 0x0D, 176, 128, 2, 100, 200, 3, 176), (4, 0x0D, 80, 80, 3, 30, 250, 1, 176),
    (1, 0x0D, 80, 144, 0, 20, 20, 0, 176),
    (7, 0x0C, 112, 80, 0, 232, 232, 0, 176), (7, 0x0C, 112, 80, 1, 20, 230, 3, 176),
    (8, 0x0C, 112, 80, 0, 60, 200, 1, 144), (8, 0x0C, 112, 80, 2, 100, 110, 1, 80),
]


def build(data, room, R):
    data = bytearray(data)
    for addr in (0x7216, 0x729E, 0x74AD):           # CPU B216, B29E, B4AD (bank at 8000: file 0x4000 + addr - 0x8000)
        assert data[addr:addr + 2] == b'\xED\x5F', hex(addr)
        data[addr:addr + 2] = bytes((0x3E, R))      # LD A,n
    m = make_machine(bytes(data))
    mem = m.memory
    mem[0xD000] = 7; mem[0xD001] = room; mem[0xD002] = data[0x1E6A + 7]; mem[0xC41A] = 0
    call(m, 0x5A49); call(m, 0x5B1B); call(m, 0x4F83)
    for w in range(4):
        m.set_memory_block(0x4000 + w * 8192, bytes(data)[w * 8192:(w + 1) * 8192])
    mem[0xD012] = 0; mem[0xC420] = 0; mem[0xCE00] = 0; mem[0xCE03] = 0
    for a in range(0xD600, 0xD700, 4): mem[a] = 0xE0
    for a in range(0xD638, 0xD680, 4): mem[a] = 0xE0
    return m, data


def run(data, room, typ, x, y, R, lo, hi, step, sy):
    m, d = build(data, room, R)
    mem = m.memory
    b = 0xC800
    mem[0xC427] = lo; mem[0xC425] = sy
    mem[b] = typ; mem[b + 3] = y; mem[b + 5] = x
    mem[b + 0x7E] = 1; mem[b + 0x7F] = 1; mem[b + 14] = 7; mem[b + 13] = d[0x20E1 + typ]
    m.ix = b
    call(m, d[0x1FCC + 2 * (typ - 1)] | d[0x1FCD + 2 * (typ - 1)] << 8)
    rows = []
    span = max(hi - lo, 0)
    for p in range(PASSES):
        t = (p * step) % (2 * span) if span else 0
        sx = lo + (2 * span - t if t > span else t)
        mem[0xC427] = sx
        if mem[b] == 0: break
        m.ix = b
        call(m, d[0x5942 + 2 * (typ - 1)] | d[0x5943 + 2 * (typ - 1)] << 8)
        call(m, 0x99B9); call(m, 0x99E5)
        bones = []
        for k in range(8):
            ib = 0xD700 + 0x80 * k
            if mem[ib] == 4:
                m.ix = ib
                call(m, 0x9F07); call(m, 0x99B9); call(m, 0x99E5)
                if mem[ib]: bones.append((mem[ib + 5], mem[ib + 3], mem[ib + 11]))
        rows.append((mem[b + 1], mem[b + 5], mem[b + 3], mem[b + 11], sorted(bones), mem[b] != 0))
        if mem[b] == 0: break
    return rows


def main():
    data = load_rom(Path(sys.argv[1]))
    out = ["/* Generated by tools/gen_stage7_vectors.py from the reference ROM routines (Z80 emulator). Do not edit. */",
           "typedef struct { int room, type, x, y, r, lo, hi, step, sy, passes; int first, bones_first; } S7Vector;",
           "static const int s7_rows[] = {"]
    vec, bonerows = [], []
    nrows = 0
    for sc in SCENARIOS:
        room, typ, x, y, R, lo, hi, step, sy = sc
        rows = run(data, room, typ, x, y, R, lo, hi, step, sy)
        vec.append((sc, len(rows), nrows))
        for st, ox, oy, pose, bones, alive in rows:
            out.append(f" {st},{ox},{oy},{pose},{len(bones)},{1 if alive else 0},")
            bonerows.extend(c for bn in bones for c in bn)
            nrows += 1
    out.append("};")
    out.append("static const int s7_bones[] = {" + ",".join(map(str, bonerows)) + (",0" if not bonerows else "") + "};")
    out.append("static const S7Vector s7_vectors[] = {")
    for sc, n, first in vec:
        room, typ, x, y, R, lo, hi, step, sy = sc
        out.append(f" {{{room},{typ},{x},{y},{R},{lo},{hi},{step},{sy},{n},{first},0}},")
    out.append("};")
    Path(sys.argv[2]).write_text("\n".join(out) + "\n")
    print(len(vec), 'scenarios', nrows, 'rows', sum(1 for _ in bonerows) // 3, 'bone samples')


if __name__ == '__main__':
    main()
