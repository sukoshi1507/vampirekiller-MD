#!/usr/bin/env python3
"""Stage 13 MSX2 ROM-only extraction. Does NOT execute Z80 or enable gameplay.

Usage: python tools/build_stage13_foundations.py /path/to/reference.rom
Never distribute the input ROM. Its SHA-256 is verified by probe.load_rom.
"""
import hashlib
import json
import sys
from pathlib import Path
from probe import load_rom
from extract_rooms import decode_room
from decode_room_links import decode, check

ROOT = Path(__file__).resolve().parents[1]
STAGE = 13
COUNT = 12
EXPECTED_NONRECIPROCAL = ['s13 r11 LEFT->9 but r9 RIGHT->10']

def extract(data):
    graph = decode(data)[STAGE]
    assert len(graph['rooms']) == COUNT
    assert check([graph]) == EXPECTED_NONRECIPROCAL
    maps, rooms = [], []
    for room in range(COUNT):
        meta, graphics, tiles = decode_room(data, STAGE, room)
        assert meta['status'] == 'static_background_decoded'
        assert len(tiles) == 768
        maps.append(tiles)
        rooms.append({'room':room,'map_cpu':meta['map_cpu'],
                      'map_file_offset':meta['map_file_offset'],
                      'map_sha256':hashlib.sha256(bytes(tiles)).hexdigest(),
                      'graphics_sha256':hashlib.sha256(graphics).hexdigest(),
                      'palette_rgb333':meta['palette_rgb333']})
    ptr_off = 0x1C5A6 + STAGE * 2
    ptr = int.from_bytes(data[ptr_off:ptr_off+2], 'little')
    assert 0x8000 <= ptr < 0xA000
    flag_off = 0x1C000 + ptr - 0x8000
    flags = list(data[flag_off:flag_off+COUNT])
    group_off = 0x1E6A + STAGE
    group = data[group_off]
    return graph,maps,rooms,flags,ptr,ptr_off,flag_off,group,group_off

def generate(data):
    graph,maps,rooms,flags,ptr,ptr_off,flag_off,group,group_off = extract(data)
    out = ROOT / 'sgdk/src/generated'
    out.mkdir(parents=True,exist_ok=True)
    lines = ['/* Stage 13 static ROM-derived resources: NOT collision maps, objects or enemy lists.',
             ' * Generated by tools/build_stage13_foundations.py. NOT connected to gameplay. */',
             '#include "stage13_foundations.h"',
             'const VKByte vk_stage13_tiles[VK_STAGE13_ROOM_COUNT][768] = {']
    for tiles in maps:
        lines.append('    {')
        lines.extend('        '+','.join(map(str, tiles[i:i+32]))+',' for i in range(0,768,32))
        lines.append('    },')
    lines.append('};')
    lines.append('const VKRoomLink vk_stage13_raw_links[VK_STAGE13_ROOM_COUNT] = {')
    for row in graph['rooms']:
        lines.append('    {'+','.join('VK_ROOM_NONE' if row[d] is None else str(row[d]) for d in ('UP','DOWN','LEFT','RIGHT'))+',0},')
    lines.append('};')
    lines.append('const VKByte vk_stage13_raw_spawn_flags[VK_STAGE13_ROOM_COUNT] = {'+','.join(map(str, flags))+'};')
    (out/'stage13_foundations.c').write_text('\n'.join(lines)+'\n')
    (out/'stage13_foundations.h').write_text('''/* Raw ROM staging: stage 13 is NOT an enabled gameplay stage. */
#ifndef VK_STAGE13_FOUNDATIONS_H
#define VK_STAGE13_FOUNDATIONS_H
#include "../room_manager.h"
#define VK_STAGE13_ROOM_COUNT 12
extern const VKByte vk_stage13_tiles[VK_STAGE13_ROOM_COUNT][768];
extern const VKRoomLink vk_stage13_raw_links[VK_STAGE13_ROOM_COUNT];
extern const VKByte vk_stage13_raw_spawn_flags[VK_STAGE13_ROOM_COUNT];
#endif
''')
    result = {
        'stage': STAGE, 'status':'raw_ROM_static_foundations_NOT_playable',
        'rom_sha256':hashlib.sha256(data).hexdigest(),
        'room_count':COUNT, 'room_navigation_pointer_cpu':f'0x{graph["pointer"]:04X}',
        'links':graph['rooms'], 'nonreciprocal_links':EXPECTED_NONRECIPROCAL,
        'rooms':rooms,
        'spawn_channel_flags':{'pointer_table_file_offset':f'0x{ptr_off:05X}',
            'pointer_cpu':f'0x{ptr:04X}', 'data_file_offset':f'0x{flag_off:05X}',
            'bytes':flags, 'note':'NOT an enemy list; do not derive enemy types from flag values'},
        'stage_group':{'file_offset':f'0x{group_off:05X}','value':group},
        'limitations':['4F83 Z80 collision maps not generated',
            '5A49/5B1B dynamic objects/doors not generated',
            '6154 fixed enemies not generated',
            'spawn flags do not identify enemy types',
            'stage-specific boss, item interactions and SFX unverified',
            'not connected to SGDK runtime','no Mega Drive build or visual verification']}
    (ROOT/'research/stage13-foundations.json').write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
    return result

if __name__=='__main__':
    if len(sys.argv)!=2: raise SystemExit(__doc__)
    report=generate(load_rom(Path(sys.argv[1])))
    print('Stage 13 ROM-only:',report['room_count'],'static maps;',report['spawn_channel_flags']['bytes'])
