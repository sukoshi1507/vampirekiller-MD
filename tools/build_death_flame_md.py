#!/usr/bin/env python3
"""Sprites of the death flame (object 1E, research/death-flame.md): two cells of four tiles (a 16x16 sprite, column by column), the
MSX patterns F4 (pose 85) and F8 (pose 86), one layer in colour 8, read in the VRAM snapshot of an openMSX run (a .vram and its .txt, taken
while a flame is on screen; the runs are not versioned). The patterns are the same in every stage (md5 checked on 8 runs).
Usage: build_death_flame_md.py SNAPSHOT.vram   (the registers are read from SNAPSHOT.txt)
"""
import sys
from pathlib import Path

vram_path = Path(sys.argv[1])
vram = vram_path.read_bytes()
regs = vram_path.with_suffix('.txt').read_text().split('\n')[0].split()[1:]
sprites = (int(regs[6]) & 0x3F) << 11          # R#6: sprite pattern generator
words = []
for pattern in (0xF4, 0xF8):
    base = sprites + pattern * 8
    pix = [[0] * 16 for _ in range(16)]
    for y in range(16):
        row = (vram[base + y] << 8) | vram[base + 16 + y]
        for x in range(16):
            if row & (0x8000 >> x):
                pix[y][x] = 8
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'death_flame_md.h').write_text("""/* Generated by tools/build_death_flame_md.py. */
#ifndef VK_DEATH_FLAME_MD_H
#define VK_DEATH_FLAME_MD_H
#include <genesis.h>
#define VK_DEATH_FLAME_TILE_COUNT 8   /* two cells of four tiles: patterns F4 (pose 85) and F8 (pose 86) */
extern const u32 vk_death_flame_tiles[64];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'death_flame_md.c').write_text('/* Generated by tools/build_death_flame_md.py. */\n#include "death_flame_md.h"\n'
                                      f'const u32 vk_death_flame_tiles[64] = {{{body}\n}};\n')
