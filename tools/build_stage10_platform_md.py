#!/usr/bin/env python3
"""Sprite of the moving platform of stage 10: patterns D8 (colour 9) and DC (colour 12, CC bit), table 906C (stage 10: rooms 0, 2, 3, 4);
Patterns come from the VRAM snapshot of an openMSX run (they are compressed in the ROM), which is not
versioned, see research/stage10-enemies.md. Usage: build_stage10_platform_md.py RUN LABEL
"""
import glob, sys
from pathlib import Path

run, label = Path(sys.argv[1]), sys.argv[2]
base = sorted(glob.glob(str(run / 'snaps' / f'*_{label}*.vram')))[0][:-5]
vram = open(base + '.vram', 'rb').read()
regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
sprites = (regs[6] & 0x3F) << 11
pix = [[0] * 16 for _ in range(16)]
for pattern, colour in ((0xD8, 9), (0xDC, 12)):
    a = sprites + pattern * 8
    for y in range(16):
        row = (vram[a + y] << 8) | vram[a + 16 + y]
        for x in range(16):
            if row & (0x8000 >> x):
                pix[y][x] |= colour
words = []
for c in range(2):
    for r in range(2):
        for y in range(8):
            v = 0
            for x in range(8):
                v = (v << 4) | pix[r * 8 + y][c * 8 + x]
            words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage10_platform_md.h').write_text(f"""/* Generated by tools/build_stage10_platform_md.py. */
#ifndef VK_STAGE10_PLATFORM_MD_H
#define VK_STAGE10_PLATFORM_MD_H
#include <genesis.h>
#define VK_STAGE10_PLATFORM_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage10_platform_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage10_platform_md.c').write_text('/* Generated by tools/build_stage10_platform_md.py. */\n'
    '#include "stage10_platform_md.h"\n'
    f'const u32 vk_stage10_platform_tiles[{len(words)}] = {{{body}\n}};\n')
print(base, ''.join('\n' + ''.join(f'{v:X}' for v in r) for r in pix))
