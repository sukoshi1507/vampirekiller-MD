#!/usr/bin/env python3
"""Sprite of the flame 26 of the dropped objects (research/candle-flames.md): the MSX pattern EC (16x16, one layer), in the three line
colours the flame cycles through, 0E, 01 and 08 (openMSX trace: colour 0E, 01, 08, 01 every 2 frames). Three cells of four tiles each
(a 16x16 sprite, column by column), in the order 0E, 01, 08. The patterns F4 and F8 of the flames 01 (C500) and 1E (C800) are the death flame
ones (build_death_flame_md.py: the same bytes, checked on a snapshot of a candle run).
Usage: build_candle_flames_md.py SNAPSHOT.vram   (the registers are read from SNAPSHOT.txt; a .vram of openMSX taken while a flame 26 is on screen)
"""
import sys
from pathlib import Path

PATTERN = 0xEC
COLOURS = (0x0E, 0x01, 0x08)

vram_path = Path(sys.argv[1])
vram = vram_path.read_bytes()
regs = vram_path.with_suffix('.txt').read_text().split('\n')[0].split()[1:]
base = (int(regs[6]) & 0x3F) << 11 | PATTERN * 8      # R#6: sprite pattern generator
bits = [[0] * 16 for _ in range(16)]
for y in range(16):
    row = (vram[base + y] << 8) | vram[base + 16 + y]
    for x in range(16):
        bits[y][x] = 1 if row & (0x8000 >> x) else 0
words = []
for colour in COLOURS:
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | (colour if bits[r * 8 + y][c * 8 + x] else 0)
                words.append(v)
n = len(words)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'candle_flames_md.h').write_text(f"""/* Generated by tools/build_candle_flames_md.py. */
#ifndef VK_CANDLE_FLAMES_MD_H
#define VK_CANDLE_FLAMES_MD_H
#include <genesis.h>
#define VK_CANDLE_FLAME_COLORS 3     /* the pattern EC in the colours 0E, 01, 08 */
extern const u32 vk_candle_flame_tiles[{n}];   /* 3 cells of 4 tiles */
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'candle_flames_md.c').write_text('/* Generated by tools/build_candle_flames_md.py. */\n#include "candle_flames_md.h"\n'
                                        f'const u32 vk_candle_flame_tiles[{n}] = {{{body}\n}};\n')
