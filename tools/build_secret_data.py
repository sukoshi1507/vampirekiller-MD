#!/usr/bin/env python3
"""ExecuteBB9A for every room; extract the completeBBCD table, without invented passages."""
import argparse
from probe import ROOT,load_rom,reference_rom
from castle_room_objects import make_machine,call
from decode_room_links import decode,cpu_to_file

def collect():
 rom=load_rom(reference_rom());machine=make_machine(rom)
 # Install the actual bank13 window; no ROM byte changes.
 machine.set_memory_block(0xA000,rom[0x1A000:0x1C000])
 counts=[len(s['rooms']) for s in decode(rom)];points=[]
 for stage in range(19):
  row=[]
  for room in range(12):
   machine.memory[0xD000]=stage;machine.memory[0xD001]=room
   machine.memory[0xC5B1:0xC5B5]=bytes(4)
   call(machine,0xBB9A)
   row.append(tuple(machine.memory[0xC5B1:0xC5B5]))
  points.append(row)
 offset=cpu_to_file(0xBBCD);raw=[]
 while rom[offset]!=255:
  stage,packed,y,x=rom[offset:offset+4];raw.append((stage,packed&15,packed>>4,x,y));offset+=4
  assert len(raw)<=228
 assert sum(bool(p[0]) for row in points for p in row)==len(raw)
 for s,r,d,x,y in raw:assert points[s][r]==(1,y,x,d)
 # Preserve the existing stage12 extraction exactly, not a replacement archive.
 from build_stage12_foundations import extract
 legacy=extract(rom)[3]
 assert [(r,d,x,y) for s,r,d,x,y in raw if s==12]==[(p['source'],p['destination'],p['x'],p['y']) for p in legacy]
 return counts,points,raw

def generate():
 counts,points,raw=collect()
 h='''/* Generated by tools/build_secret_data.py via executedBB9A and completeBBCD. */
#ifndef VK_SECRET_DATA_H
#define VK_SECRET_DATA_H
#include "../player.h"
#define VK_SECRET_STAGES 19
#define VK_SECRET_ROOMS 12
extern const VKByte vk_secret_points[19][12][4]; /* C5B1 flag,Y,X,destination */
extern const VKByte vk_secret_room_counts[19];
#endif
'''
 c='/* Generated by tools/build_secret_data.py. Never edit manually. */\n#include "secret_data.h"\n'
 c+='const VKByte vk_secret_room_counts[19]={'+','.join(map(str,counts))+'};\n'
 c+='const VKByte vk_secret_points[19][12][4]={\n'+''.join(' {'+','.join('{'+','.join(map(str,p))+'}' for p in row)+'},\n' for row in points)+'};\n'
 return {'secret_data.h':h,'secret_data.c':c},counts,raw

