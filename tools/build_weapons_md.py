#!/usr/bin/env python3
"""Generate the sprites of the thrown weapons (C450/C460 slots) for SGDK.

Usage: scratchpad/venv/bin/python tools/build_weapons_md.py ROM [PREVIEW.png]
Writes sgdk/src/generated/weapons_md.c and .h (never hand edit).

Sources (research/secondary-weapons.md), RLE of 46F1 decoded from the ROM with
bank 9 at 8000 and bank 10 at A000 (537A):
  - 5593 (each throw, C416 >= 2): table 55D7[C416 - 2] = A24E (dagger, 1 frame),
    A4C9 (axe, 2 frames), A272 (cross, 2 frames) to sprite patterns 18.. (F8C0);
    473E then mirrors them (477F, bit-reversed rows, halves swapped): dagger
    18 -> 20 (55E7), axe and cross 18 -> 30 (55DD) and 20 -> 28 (55E2);
  - holy water (object 1E): bottle pattern 38 (A147 -> F9C0, 5777), flames F4 and
    F8 (A185 -> FF00, 5768: patterns E0.., F4 at offset A0h).
Every frame is two 16x16 layers, pattern N and N + 4 (7535: D61A = N, D61E = N + 4).
Colours (7575, colour tables D460/D480): dagger, axe, holy water: layer 0 colour 2,
layer 1 colour 4Ch (C with CC: ORed, 2 | C = E where both are set); cross: 0Fh and
0Eh without CC (layer 0 wins where both are set, lower sprite number); holy water
flames (state 3, 75A9): colour 8, layer 1 colour 0 (transparent).
Checked against openMSX VRAM snapshots (scratchpad, research note).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))

from probe import load_rom  # noqa: E402
from extract_rooms import RomView  # noqa: E402
from extract_player import decode_rle  # noqa: E402

OUT = ROOT / 'sgdk/src/generated'


def mirror(sprite):
    """477F: each 16x16 layer (32 bytes, left column then right column) mirrored."""
    rev = [int(f'{b:08b}'[::-1], 2) for b in range(256)]
    out = bytearray(32)
    for i in range(16):
        out[16 + i] = rev[sprite[i]]
        out[i] = rev[sprite[16 + i]]
    return bytes(out)


def pixels(layer):
    """16x16 mask of one MSX sprite pattern (32 bytes)."""
    return [[(layer[(x // 8) * 16 + y] >> (7 - x % 8)) & 1 for x in range(16)] for y in range(16)]


def compose(l0, l1, c0, c1, cc):
    a, b = pixels(l0), pixels(l1)
    img = []
    for y in range(16):
        row = []
        for x in range(16):
            if cc:
                row.append((c0 if a[y][x] else 0) | (c1 if b[y][x] else 0))
            else:
                row.append(c0 if a[y][x] else (c1 if b[y][x] else 0))
        img.append(row)
    return img


def tiles(img):
    """SGDK sprite order: column-major (TL, BL, TR, BR), 4 bpp rows."""
    out = []
    for cx in (0, 8):
        for cy in (0, 8):
            for y in range(8):
                w = 0
                for x in range(8):
                    w = (w << 4) | img[cy + y][cx + x]
                out.append(w)
    return out


def main():
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 1
    data = load_rom(Path(sys.argv[1]))
    view = RomView(data, (0, 1, 9, 10))
    pat = {}

    def frame2(raw):                 # two layers of one frame
        return raw[0:32], raw[32:64]

    dagger = decode_rle(view, 0xA24E)
    axe = decode_rle(view, 0xA4C9)
    cross = decode_rle(view, 0xA272)
    assert len(dagger) == 64 and len(axe) == 128 and len(cross) == 128
    frames = []                      # (name, layer0, layer1, c0, c1, cc)
    d18 = frame2(dagger)
    frames.append(('dagger 18 (left)', *d18, 2, 0xC, True))
    frames.append(('dagger 20 (right)', mirror(d18[0]), mirror(d18[1]), 2, 0xC, True))
    for name, raw, c0, c1, cc in (('axe', axe, 2, 0xC, True), ('cross', cross, 0xF, 0xE, False)):
        p18, p20 = frame2(raw[:64]), frame2(raw[64:])
        p28 = (mirror(p20[0]), mirror(p20[1]))
        p30 = (mirror(p18[0]), mirror(p18[1]))
        for n, p in (('18', p18), ('20', p20), ('28', p28), ('30', p30)):
            frames.append((f'{name} {n}', *p, c0, c1, cc))
    bottle = decode_rle(view, 0xA147)
    frames.append(('holy water 38', bottle[0:32], bottle[32:64], 2, 0xC, True))
    flames = decode_rle(view, 0xA185)
    for n, off in (('F4', 0xA0), ('F8', 0xC0)):
        frames.append((f'holy water flame {n}', flames[off:off + 32], bytes(32), 8, 0, True))

    images = [compose(f[1], f[2], f[3], f[4], f[5]) for f in frames]
    words = []
    for img in images:
        words.extend(tiles(img))
    src = ['/* Generated by tools/build_weapons_md.py. Never hand edit. */',
           '#include "weapons_md.h"', '',
           '/* Frames (4 sprite tiles each, MSX colour indices = PAL2 of the room):']
    for i, f in enumerate(frames):
        src.append(f' *   {i:2d} {f[0]}')
    src += [' */', f'const u32 vk_weapon_tiles[{len(words)}] = {{']
    for i in range(0, len(words), 8):
        src.append('    ' + ', '.join(f'0x{w:08X}UL' for w in words[i:i + 8]) + ',')
    src += ['};', '']
    hdr = ['/* Generated by tools/build_weapons_md.py. Never hand edit. */',
           '#ifndef VK_WEAPONS_MD_H', '#define VK_WEAPONS_MD_H', '#include <genesis.h>',
           f'#define VK_WEAPON_FRAMES {len(frames)}',
           '#define VK_WEAPON_TILES_PER_FRAME 4',
           '#define VK_WEAPON_FRAME_DAGGER 0      /* + 1 facing right (pattern 20) */',
           '#define VK_WEAPON_FRAME_AXE 2         /* + (pattern - 18) / 8 */',
           '#define VK_WEAPON_FRAME_CROSS 6       /* + (pattern - 18) / 8 */',
           '#define VK_WEAPON_FRAME_BOTTLE 10',
           '#define VK_WEAPON_FRAME_FLAME 11      /* + 1 for pattern F8 */',
           'extern const u32 vk_weapon_tiles[VK_WEAPON_FRAMES * VK_WEAPON_TILES_PER_FRAME * 8];',
           '#endif', '']
    (OUT / 'weapons_md.c').write_text('\n'.join(src))
    (OUT / 'weapons_md.h').write_text('\n'.join(hdr))
    if len(sys.argv) == 3:
        from PIL import Image
        pal = [(0, 0, 0), (0, 0, 0), (36, 219, 36), (109, 255, 109), (36, 36, 255), (73, 109, 255),
               (182, 36, 36), (73, 219, 255), (255, 36, 36), (255, 109, 109), (219, 219, 36),
               (219, 219, 146), (36, 146, 36), (219, 73, 182), (182, 182, 182), (255, 255, 255)]
        sheet = Image.new('RGB', (18 * len(images), 16), (40, 40, 40))
        for i, img in enumerate(images):
            for y in range(16):
                for x in range(16):
                    if img[y][x]:
                        sheet.putpixel((18 * i + x, y), pal[img[y][x]])
        sheet.resize((sheet.width * 4, 64), Image.NEAREST).save(sys.argv[2])
    print(f'{len(frames)} frames')
    return 0


if __name__ == '__main__':
    sys.exit(main())
