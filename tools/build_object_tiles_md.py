#!/usr/bin/env python3
"""Generate the object, HUD digit, font and wall object tiles for SGDK.

Usage: scratchpad/venv/bin/python tools/build_object_tiles_md.py [SNAPSHOT_BASE]
Writes sgdk/src/generated/object_tiles_md.c and .h (never hand edit).

Objects are not sprites on the MSX, they are copied with transparency into the
SCREEN 5 bitmap from VRAM page 1 (object k at x 16*((k-1) mod 16),
y 336 + 16*((k-1) div 16); 0x21 and 0x22 are the two wall candle frames). The
HUD digits 0-9 sit at y 320, x 0..79 of the same page; they are the codes
0x20..0x29 of the text font of 4AE7/4B41 (code c at x 8*(c & 1F),
y 256 + 38h + (c & E0) / 4), exported for the codes 0x20..0x5F. The five frames
of the old man (925E: page 1, x 32 x frame, y A0h, 32 x 32, copied with TIMP) are
exported from y A8h on (32 x 24): their first 8 rows are empty. The page is read
from an openMSX VRAM snapshot (hall room 2, not versioned). Pixels are MSX palette
indices, i.e. PAL0 indices on the MD.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'sgdk/src/generated'
DEFAULT_SNAPSHOT = ROOT / 'scratchpad/type5/out/A/snaps/f02958_r2_8084888C'
OBJECT_COUNT = 0x22               # sheet entries 1..0x22
PAGE1 = 256
DIGIT_Y = PAGE1 + 64
SHEET_Y = PAGE1 + 80
FONT_FIRST, FONT_COUNT = 0x20, 0x40
WALL_FRAMES, WALL_Y = 5, PAGE1 + 0xA8


def pixel_reader(base):
    vram = Path(str(base) + '.vram').read_bytes()

    def pixel(x, y):
        byte = vram[y * 128 + x // 2]
        return byte >> 4 if x % 2 == 0 else byte & 15
    return pixel


def tile(pixel, x0, y0):
    words = []
    for row in range(8):
        word = 0
        for x in range(8):
            word = (word << 4) | pixel(x0 + x, y0 + row)
        words.append(word)
    return words


def sprite_tiles(pixel, x0, y0, cols=2, rows=2):
    """Block in SGDK sprite order: column-major."""
    out = []
    for cx in range(0, cols * 8, 8):
        for cy in range(0, rows * 8, 8):
            out.extend(tile(pixel, x0 + cx, y0 + cy))
    return out


def words(values):
    return ['    ' + ' '.join(f'0x{v:08X}UL,' for v in values[i:i + 8]) for i in range(0, len(values), 8)]


def main():
    pixel = pixel_reader(Path(sys.argv[1]) if len(sys.argv) == 2 else DEFAULT_SNAPSHOT)
    sheet = []
    for k in range(1, OBJECT_COUNT + 1):
        sheet.extend(sprite_tiles(pixel, 16 * ((k - 1) % 16), SHEET_Y + 16 * ((k - 1) // 16)))
    digits = []
    for d in range(10):
        digits.extend(tile(pixel, 8 * d, DIGIT_Y))
    font = []
    for c in range(FONT_FIRST, FONT_FIRST + FONT_COUNT):
        font.extend(tile(pixel, 8 * (c & 0x1F), PAGE1 + 0x38 + ((c & 0xE0) >> 2)))
    frames = []
    for f in range(WALL_FRAMES):
        frames.extend(sprite_tiles(pixel, 32 * f, WALL_Y, 4, 3))
    src = ['/* Generated by tools/build_object_tiles_md.py. Never hand edit. */',
           '#include "object_tiles_md.h"', '',
           f'/* Objects 1..0x{OBJECT_COUNT:02X}, 4 sprite tiles each (PAL0 indices). */',
           f'const u32 vk_object_tiles[{len(sheet)}] = {{'] + words(sheet) + ['};', '',
           '/* HUD digits 0-9 (PAL0 indices). */',
           f'const u32 vk_hud_digit_tiles[{len(digits)}] = {{'] + words(digits) + ['};', '',
           f'/* Text font codes 0x{FONT_FIRST:02X}..0x{FONT_FIRST + FONT_COUNT - 1:02X} (ASCII - 0x10): 0 background, 14 ink. */',
           f'const u32 vk_msx_font_tiles[{len(font)}] = {{'] + words(font) + ['};', '',
           f'/* Old man frames 0..{WALL_FRAMES - 1} (925E), 32 x 24 from page 1 y A8h, 4 x 3 sprite tiles each. */',
           f'const u32 vk_wall_frame_tiles[{len(frames)}] = {{'] + words(frames) + ['};', '']
    header = ['/* Generated by tools/build_object_tiles_md.py. Never hand edit. */',
              '#ifndef VK_OBJECT_TILES_MD_H', '#define VK_OBJECT_TILES_MD_H', '#include <genesis.h>',
              f'extern const u32 vk_object_tiles[{len(sheet)}];',
              f'extern const u32 vk_hud_digit_tiles[{len(digits)}];',
              f'#define VK_MSX_FONT_FIRST 0x{FONT_FIRST:02X}', f'#define VK_MSX_FONT_COUNT {FONT_COUNT}',
              f'extern const u32 vk_msx_font_tiles[{len(font)}];',
              f'#define VK_WALL_FRAME_COUNT {WALL_FRAMES}', '#define VK_WALL_TILES_PER_FRAME 12',
              f'extern const u32 vk_wall_frame_tiles[{len(frames)}];', '#endif', '']
    (OUT / 'object_tiles_md.c').write_text('\n'.join(src))
    (OUT / 'object_tiles_md.h').write_text('\n'.join(header))
    print(f'{OBJECT_COUNT} objects, {WALL_FRAMES} wall frames')
    return 0


if __name__ == '__main__':
    sys.exit(main())
