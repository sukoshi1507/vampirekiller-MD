#!/usr/bin/env python3
"""Sprites of the stage 11 objects, in the layout of the type 5 block (pattern N is tile N - 0x40, a cell is four tiles).
Patterns come from VRAM snapshots of openMSX runs (compressed in the ROM; runs not versioned, see research/stage11-enemies.md). The two layers of a pair
(pattern N in colour a, N + 4 in colour b with the CC bit = OR) are composed in one cell. Destination cell <- source pattern :
  40 48 50 58 60 68 70 <- 40 48 50 58 60 68 70  eagle (object 0F), colours 1 and 2, trace run R room 2
  80 84 88 8C <- A8 B0 C0 C8                    flea (objects 0D and 23h), colours 2 and 5 (run R room 2)
  90 <- 80, 94 <- 78, 98 <- 70                  dragon (object 0E) closed head, body, open head, colours 2 and 12 (run R5, room 5)
  9C <- F0                                      the shot (D700 type 1), colour 8
  A0, A4 <- ghost 1B (candles of object 15), when ghost snapshots are given as a second argument.
Object 1B (candles of object 15, D002 = 3) : vk_stage11_ghost_tiles[variant][2 cells], variant 0 = pose base 9B (D0 + D8, D4 + DC ; rooms 0), variant 1 = pose base A1
(A0 + D8, A4 + DC ; room 5), colours 8 and 2 (CC), runs G and G5 (candle hit by the whip, stage and room forced).
Usage: build_stage11_enemies_md.py RUN_R RUN_R5 RUN_G RUN_G5"""
import glob
import sys
from pathlib import Path

runs = [Path(a) for a in sys.argv[1:]]
sys.argv = sys.argv[:1]


def snaps(run):
    return sorted(glob.glob(str(run / 'snaps' / '*.vram')))


def pix_of(base, pattern, colour):
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    sprites = (regs[6] & 0x3F) << 11
    a = sprites + pattern * 8
    return [[colour if ((vram[a + y] << 8) | vram[a + 16 + y]) & (0x8000 >> x) else 0 for x in range(16)] for y in range(16)]


def snap_with(run, room, pair):
    """A snapshot of the room where the pair is in the SAT (the name lists the patterns)."""
    for f in snaps(run):
        name = Path(f).name
        if f'_r{room}_' in name and pair in name.split('_', 2)[2]:
            return f[:-5]
    raise SystemExit(f'no snapshot with {pair} in room {room}')


def compose(base, src, colours):
    out = [[0] * 16 for _ in range(16)]
    for k, c in enumerate(colours):
        layer = pix_of(base, src + 4 * k, c)
        for y in range(16):
            for x in range(16):
                out[y][x] |= layer[y][x]
    return out


cells = {}
R, R5 = runs[0], runs[1]
for n in (0x40, 0x48, 0x50, 0x58, 0x60, 0x68, 0x70):
    cells[n] = compose(snap_with(R, 2, f'{n:02X}{n + 4:02X}'), n, (1, 2))
for dest, n in ((0x80, 0xA8), (0x84, 0xB0), (0x88, 0xC0), (0x8C, 0xC8)):
    cells[dest] = compose(snap_with(R, 2, f'{n:02X}{n + 4:02X}'), n, (2, 5))
for dest, n in ((0x90, 0x80), (0x94, 0x78), (0x98, 0x70)):
    cells[dest] = compose(snap_with(R5, 5, f'{n:02X}{n + 4:02X}'), n, (2, 12))
fire = [f for f in snaps(R5) if '_r5_' in f or True]
cells[0x9C] = None
for f in snaps(R5):
    try:
        p = pix_of(f[:-5], 0xF0, 8)
    except Exception:
        continue
    if any(any(r) for r in p):
        cells[0x9C] = p
        break
G, G5 = runs[2], runs[3]


def ghost(run, room, p1, p2):
    base = snap_with(run, room, f'{p1:02X}{p2:02X}')
    out = [[0] * 16 for _ in range(16)]
    for pat, c in ((p1, 8), (p2, 2)):
        layer = pix_of(base, pat, c)
        for y in range(16):
            for x in range(16):
                out[y][x] |= layer[y][x]
    return out


def cell_words(pix):
    out = []
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                out.append(v)
    return out


ghostwords = (cell_words(ghost(G, 0, 0xD0, 0xD8)) + cell_words(ghost(G, 0, 0xD4, 0xDC)) +
              cell_words(ghost(G5, 5, 0xA0, 0xD8)) + cell_words(ghost(G5, 5, 0xA4, 0xDC)))

words = []
for pattern in range(0x40, 0xC0, 4):
    pix = cells.get(pattern) or [[0] * 16 for _ in range(16)]
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage11_enemies_md.h').write_text(f"""/* Generated by tools/build_stage11_enemies_md.py. */
#ifndef VK_STAGE11_ENEMIES_MD_H
#define VK_STAGE11_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE11_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage11_enemy_tiles[{len(words)}];
#define VK_STAGE11_GHOST_TILE_COUNT 8
extern const u32 vk_stage11_ghost_tiles[2][64];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage11_enemies_md.c').write_text('/* Generated by tools/build_stage11_enemies_md.py. */\n#include "stage11_enemies_md.h"\n'
                                         f'const u32 vk_stage11_enemy_tiles[{len(words)}] = {{{body}\n}};\n'
                                         'const u32 vk_stage11_ghost_tiles[2][64] = {' + ''.join(('\n    {' if k % 64 == 0 else '') + ('\n     ' if k % 8 == 0 else ' ') + f'0x{x:08X},' + ('},' if k % 64 == 63 else '') for k, x in enumerate(ghostwords)) + '\n};\n')
print(len(words) // 8, 'tiles;', sorted(hex(k) for k, v in cells.items() if v))
