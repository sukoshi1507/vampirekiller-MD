#!/usr/bin/env python3
"""Execute6333 and the real background copies; compile six room views and four busts."""
import argparse,json
from probe import ROOT
from dracula_graphics import room,tiles

def generate():
 h=room();base=bytes(h.vram);words=[];lookup={};maps=[];rawmaps=[]
 for upper in range(2):
  for lower in range(3):
   h.vram[:]=base;h.call(0x69A0 if upper else 0x6984);h.call((0x6914,0x68DC,0x694C)[lower])
   raw=tiles(h,0,32,256,176);mapping=[]
   for i in range(0,len(raw),8):
    tile=tuple(raw[i:i+8])
    if tile not in lookup:lookup[tile]=len(words)//8;words.extend(tile)
    mapping.append(lookup[tile])
   maps.append(mapping);rawmaps.append(bytes(h.vram[32*128:192*128]).hex())
 bust=[]
 for x in (0,32,64,96):bust.extend(tiles(h,x,384,32,32,True))
 assert any(bust), "empty bust"

 initial_palette=list(h.vram[0xF680:0xF6A0]);palette=[]
 for r,g,b in h.palette:palette.append((b*2<<8)|(g*2<<4)|r*2)
 # Every list of layers the bust script (dracula.c, case 1) can build: an ordered subset of 1..4 (a layer shown again moves to the end).
 # Composed here in the order the layers are applied (the opaque pixels of a layer replace those below): the game only queues a DMA.
 import itertools
 sets=[];set_of=[255]*625
 for k in range(5):
  for perm in itertools.permutations((1,2,3,4),k):
   row=[0]*128
   for layer in perm:
    for i in range(128):
     w=bust[(layer-1)*128+i];m=sum(0xF<<(4*n) for n in range(8) if w>>(4*n)&15);row[i]=(row[i]&~m)|w
   set_of[sum(l*5**q for q,l in enumerate(perm))]=len(sets);sets.append(row)
 header=f'''/* Generated by tools/build_dracula_background.py via6333/5880/57DF. */
#ifndef VK_DRACULA_BACKGROUND_H
#define VK_DRACULA_BACKGROUND_H
#include <genesis.h>
#define VK_DRACULA_BACKGROUND_TILES {len(words)//8}
#define VK_DRACULA_BUST_SETS {len(sets)}
extern const u32 vk_dracula_background_tiles[{len(words)}];
extern const u16 vk_dracula_background_map[6][704];
extern const u16 vk_dracula_background_palette[16];
extern const u8 vk_dracula_initial_palette[32];
extern const u32 vk_dracula_bust_tiles[512];
extern const u32 vk_dracula_bust_sets[VK_DRACULA_BUST_SETS][128];
extern const u8 vk_dracula_bust_set_of[625];
#endif
'''
 data='/* Generated by tools/build_dracula_background.py. */\n#include "dracula_background.h"\n'
 def array(name,kind,values,width):
  return f'const {kind} {name}={{\n'+''.join(' '+','.join((f'0x{v:08X}' if kind=='u32' else str(v)) for v in values[i:i+width])+',\n' for i in range(0,len(values),width))+'};\n'
 data+=array(f'vk_dracula_background_tiles[{len(words)}]','u32',words,8)
 data+=array('vk_dracula_background_palette[16]','u16',palette,16)
 data+=array('vk_dracula_initial_palette[32]','u8',initial_palette,16)
 data+=array('vk_dracula_bust_tiles[512]','u32',bust,8)
 data+='const u32 vk_dracula_bust_sets[VK_DRACULA_BUST_SETS][128]={\n'+''.join(' {'+','.join(f'0x{v:08X}' for v in row)+'},\n' for row in sets)+'};\n'
 data+=array('vk_dracula_bust_set_of[625]','u8',set_of,25)
 data+='const u16 vk_dracula_background_map[6][704]={\n'+''.join(' {'+','.join(map(str,m))+'},\n' for m in maps)+'};\n'
 return {'dracula_background.h':header,'dracula_background.c':data},{'words':words,'maps':maps,'bust':bust,'palette':palette}

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
 output,meta=generate()
 for name,s in output.items():
  dest=ROOT/'sgdk/src/generated'/name
  if a.check:assert dest.read_text()==s,name
  else:dest.write_text(s)
 print('Dracula background:6 views,',len(meta['words'])//8,'tiles,4 busts','CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
