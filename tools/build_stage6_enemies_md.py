#!/usr/bin/env python3
"""Sprites of the stage 6 objects, in the layout of the type 5 block (pattern N is tile N - 0x40, a cell is
four tiles). Patterns come from VRAM snapshots of openMSX runs (they are compressed in the ROM, 46F1); the
runs are not versioned, see research/stage6-enemies.md. Cells (destination pattern, source pattern, colours):
  40 48 50 58   object 08 (rooms 3 and 4), layers N and N+4, colours 2 and 5
  A0 A8 B0 B8   object 07, the bat, layers N and N+4, colours 2 and 12 (CC)
  44 4C / 54 5C statue 0A, top and bottom, eyes colour 12 / 8 (4C and 48 in the SAT)
  60            fireball (D700 type 3), pattern F0 colour 8
  64 68 6C 70   chain strip of the crushers: 16, 4, 8 and 12 rows from the top
  74 78         body of a crusher: 32 x 16 from page 1 of the VRAM at (80h, 70h)
Usage: build_stage6_enemies_md.py RUN
"""
import glob, sys
from pathlib import Path

run = Path(sys.argv[1])
cells = {}   # destination pattern -> 16 x 16 pixels


def snap(label):
    base = sorted(glob.glob(str(run / 'snaps' / f'*_{label}.vram')))[0][:-5]
    vram = open(base + '.vram', 'rb').read()
    regs = [int(x) for x in open(base + '.txt').read().split('\n')[0].split()[1:]]
    return vram, (regs[6] & 0x3F) << 11


def layers(label, dest, *spec):
    vram, sprites = snap(label)
    pix = [[0] * 16 for _ in range(16)]
    for pattern, colour in spec:
        a = sprites + pattern * 8
        for y in range(16):
            row = (vram[a + y] << 8) | vram[a + 16 + y]
            for x in range(16):
                if row & (0x8000 >> x):
                    pix[y][x] |= colour
    cells[dest] = pix


for n in (0x40, 0x48, 0x50, 0x58):
    layers('r3', n, (n, 2), (n + 4, 5))
for n in (0xA0, 0xA8, 0xB0, 0xB8):
    layers('r0', n, (n, 2), (n + 4, 12))
layers('r2', 0x44, (0xC0, 2), (0xC4, 12))
layers('r2', 0x4C, (0xC8, 2), (0xCC, 12))
layers('r2', 0x54, (0xC0, 2), (0xC4, 8))
layers('r2', 0x5C, (0xC8, 2), (0xCC, 8))
layers('r2', 0x60, (0xF0, 8))

# Crusher: the 32 x 16 image copied by 4946 from (80h, 70h) of page 1 (4 bits per pixel, 128 bytes a row).
vram, _ = snap('r1')
img = [[(vram[0x8000 + (0x70 + y) * 128 + (0x80 + x) // 2] >> (4 if x % 2 == 0 else 0)) & 15 for x in range(32)] for y in range(16)]
cells[0x74] = [row[0:16] for row in img]
cells[0x78] = [row[16:32] for row in img]
# Chain: the top 4 rows of the image, columns 8 to 23, repeated; a cell with fewer rows is blank below.
for dest, rows in ((0x64, 16), (0x68, 4), (0x6C, 8), (0x70, 12)):
    cells[dest] = [img[y % 4][8:24] if y < rows else [0] * 16 for y in range(16)]

words = []
for pattern in range(0x40, 0xC0, 4):
    pix = cells.get(pattern, [[0] * 16 for _ in range(16)])
    for c in range(2):
        for r in range(2):
            for y in range(8):
                v = 0
                for x in range(8):
                    v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'stage6_enemies_md.h').write_text(f"""/* Generated by tools/build_stage6_enemies_md.py. */
#ifndef VK_STAGE6_ENEMIES_MD_H
#define VK_STAGE6_ENEMIES_MD_H
#include <genesis.h>
#define VK_STAGE6_ENEMY_TILE_COUNT {len(words) // 8}
extern const u32 vk_stage6_enemy_tiles[{len(words)}];
#endif
""")
body = ''.join(('\n    ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(words))
(out / 'stage6_enemies_md.c').write_text('/* Generated by tools/build_stage6_enemies_md.py. */\n#include "stage6_enemies_md.h"\n'
    f'const u32 vk_stage6_enemy_tiles[{len(words)}] = {{{body}\n}};\n')
for dest in sorted(cells):
    print(hex(dest), sum(1 for row in cells[dest] if any(row)), 'rows')
