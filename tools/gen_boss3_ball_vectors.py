#!/usr/bin/env python3
"""Vectors for tests/test_boss3_ball.c: the fireball of the stage 3 boss (object 12h, D700 type 01) created by the ROM routine 9F61 and moved by the
ROM D700 loop 9E31 (type routine 9E58, move 99B9, draw 6445, exit test 99E5: Y >= E4h, X >= F1h or X < 7) in the kosarev/z80 emulator, stage 3 room 5.
A row is (Y low, Y high, X low, X high, vy, vx at creation, passes the ball stays alive, Y high and X high of the last pass it is alive).
Usage: gen_boss3_ball_vectors.py ROM OUT.h"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from castle_room_objects import make_machine, call
from probe import load_rom

# Start (boss X, boss Y; the ball is created at (X, Y - 16)), vy and vx (8.8): every direction and speed range of the fight, the edges and the wrap above Y 0.
STARTS = ((100, 100), (30, 120), (210, 96), (128, 40), (128, 20), (10, 90), (240, 90), (60, 224), (200, 130))
SPEEDS = ((0x0200, 0x0300), (0x0200, -0x0300), (-0x0200, 0x0100), (-0x0400, 0), (0x0100, 0x0400), (0, -0x0400), (0x0300, 0), (-0x0100, -0x0100),
          (-0x0600, 0x0080), (0x0040, 0x0040))
MAX_PASSES = 400


def build(data):
    m = make_machine(bytes(data))
    mem = m.memory
    mem[0xD000] = 3; mem[0xD001] = 5; mem[0xD002] = data[0x1E6A + 3]; mem[0xC41A] = 0
    call(m, 0x5A49); call(m, 0x5B1B); call(m, 0x4F83)
    for w in range(4):
        m.set_memory_block(0x4000 + w * 8192, bytes(data)[w * 8192:(w + 1) * 8192])
    mem[0xD012] = 0; mem[0xC420] = 0; mem[0xCE00] = 0; mem[0xCE03] = 0; mem[0xD010] = 0
    for a in range(0xD600, 0xD700, 4): mem[a] = 0xE0
    for k in range(7):
        for i in range(0x80): mem[0xC800 + 0x80 * k + i] = 0
    for k in range(8):
        for i in range(0x80): mem[0xD700 + 0x80 * k + i] = 0
    return m


def run(data, bx, by, vy, vx):
    m = build(data)
    mem = m.memory
    b = 0xC800
    mem[b] = 0x12; mem[b + 3] = by; mem[b + 5] = bx; mem[b + 0x7E] = 1; mem[b + 0x7F] = 1
    m.ix = b; m.hl = vy & 0xFFFF; m.de = vx & 0xFFFF
    call(m, 0x9F61)
    d = 0xD700
    if mem[d] != 1:
        return None
    start = (mem[d + 2], mem[d + 3], mem[d + 4], mem[d + 5], mem[d + 7] | mem[d + 8] << 8, mem[d + 9] | mem[d + 10] << 8)
    alive, last = 0, (mem[d + 3], mem[d + 5])
    for p in range(MAX_PASSES):
        call(m, 0x9E31)
        if mem[d] == 0:
            break
        alive += 1
        last = (mem[d + 3], mem[d + 5])
    else:
        return None
    return start + (alive,) + last


def main():
    data = load_rom(Path(sys.argv[1]))
    rows = []
    for bx, by in STARTS:
        for vy, vx in SPEEDS:
            r = run(data, bx, by, vy, vx)
            if r:
                rows.append(r)
    out = ["/* Generated by tools/gen_boss3_ball_vectors.py from the reference ROM routines (Z80 emulator). Do not edit. */",
           "static const int boss3_ball_rows[][9] = {"]
    out += [" {%d,%d,%d,%d,%d,%d,%d,%d,%d}," % r for r in rows]
    out += ["};", "#define BOSS3_BALL_ROWS %d" % len(rows)]
    Path(sys.argv[2]).write_text('\n'.join(out) + '\n')
    print(len(rows), 'ball trajectories')


if __name__ == '__main__':
    main()
