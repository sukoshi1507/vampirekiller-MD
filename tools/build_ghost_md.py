#!/usr/bin/env python3
"""Sprites of the object 1C released by the candles of object 15 (research/stage9-candle-object.md), in the layout of the type 5 block
(a cell is four tiles, column by column). Three variants, by the pose base of the room (table B642): 9B, 9F and A1. Each pose is a
cell made of two sprite layers: pattern a in colour 14 and pattern b in colour 2 (CC = OR), read in the VRAM snapshot of an openMSX run
(snap.vram, snap.txt of the run, taken while the object rests; the runs are not versioned):
  9B  poses 9B (D0, D8) and 9C (D4, DC)   stage 7 room 3
  9F  poses 9F (70, 78) and A0 (74, 7C)   stage 9 room 2
  A1  poses A1 (A0, D8) and A2 (A4, DC)   stage 7 room 1
The cells go to B4 (odd pose) and B8 (even pose) of the enemy block of the stages 7, 8 and 9 (free there).
Usage: build_ghost_md.py RUN_9B RUN_9F RUN_A1
"""
import sys
from pathlib import Path

runs = [Path(a) for a in sys.argv[1:4]]
poses = [((0xD0, 0xD8), (0xD4, 0xDC)), ((0x70, 0x78), (0x74, 0x7C)), ((0xA0, 0xD8), (0xA4, 0xDC))]
words = []
for run, variant in zip(runs, poses):
    vram = (run / 'snap.vram').read_bytes()
    regs = (run / 'snap.txt').read_text().split('\n')[0].split()
    sprites = (int(regs[regs.index('r6') + 1]) & 0x3F) << 11
    for a, b in variant:
        pix = [[0] * 16 for _ in range(16)]
        for pattern, colour in ((a, 14), (b, 2)):
            base = sprites + pattern * 8
            for y in range(16):
                row = (vram[base + y] << 8) | vram[base + 16 + y]
                for x in range(16):
                    if row & (0x8000 >> x):
                        pix[y][x] |= colour
        for c in range(2):
            for r in range(2):
                for y in range(8):
                    v = 0
                    for x in range(8):
                        v = (v << 4) | pix[r * 8 + y][c * 8 + x]
                    words.append(v)
out = Path(__file__).resolve().parents[1] / 'sgdk/src/generated'
(out / 'ghost_md.h').write_text(f"""/* Generated by tools/build_ghost_md.py. */
#ifndef VK_GHOST_MD_H
#define VK_GHOST_MD_H
#include <genesis.h>
#define VK_GHOST_TILE_COUNT 8   /* two cells of four tiles per variant */
extern const u32 vk_ghost_tiles[3][{len(words) // 3}];
#endif
""")
body = ''
for v in range(3):
    chunk = words[v * 64:(v + 1) * 64]
    body += '    {' + ''.join(('\n        ' if i % 8 == 0 else ' ') + f'0x{x:08X},' for i, x in enumerate(chunk)) + '\n    },\n'
(out / 'ghost_md.c').write_text('/* Generated by tools/build_ghost_md.py. */\n#include "ghost_md.h"\n'
                                f'const u32 vk_ghost_tiles[3][{len(words) // 3}] = {{\n{body}}};\n')
