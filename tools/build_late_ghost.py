#!/usr/bin/env python3
"""Execute1B constructor/B611 for every late room; no invented pose bases."""
import argparse
from probe import ROOT,load_rom,reference_rom
from castle_room_objects import make_machine,call
from decode_room_links import decode

def generate():
 rom=load_rom(reference_rom());rows=[]
 for graph in decode(rom)[12:]:
  row=[]
  for room in range(12):
   if room>=len(graph['rooms']):row.append(0);continue
   m=make_machine(rom);mem=m.memory;mem[0xD000]=graph['stage'];mem[0xD001]=room;mem[0xD002]=rom[0x1E6A+graph['stage']]
   for a in range(0xD600,0xD700,4):mem[a]=224
   assert rom[0x4AF0+mem[0xD002]-1]==27,'8AF0 late candle species'
   m.c=27;m.de=0x80A0;call(m,0x5F1D);row.append(mem[0xC80B]);assert mem[0xC800]==27
  rows.append(row)
 return '/* Generated by build_late_ghost.py: executed1B constructor/B611. */\nstatic const EnemyU8 late_ghost_base[7][12]={'+','.join('{'+','.join(map(str,r))+'}' for r in rows)+'};\n'
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();t=generate();f=ROOT/'sgdk/src/generated/late_ghost.h'
 if a.check:assert f.read_text()==t
 else:f.write_text(t)
 print('Late1B:74 executed room pose bases', 'CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
