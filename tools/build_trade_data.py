#!/usr/bin/env python3
"""Execute5A49/5B1B for every room; extract5B0B,9300/9320 and nine prices9428."""
import argparse
from probe import ROOT,load_rom,reference_rom
from build_candles_md import decode_wall,ROOMS
from castle_room_objects import decode_room
from decode_room_links import decode

def collect():
 rom=load_rom(reference_rom());counts=dict(ROOMS);counts.update({s['stage']:len(s['rooms']) for s in decode(rom) if s['stage']>=12})
 assert rom[0x540C:0x540E]==bytes([6,9]),'940C must bound price scan to9'
 defs=[];first=[];items=[];blocks=[]
 for stage in range(19):
  row=[];itrow=[]
  for room in range(12):
   row.append(len(defs))
   if room>=counts[stage]:itrow.append((0,0));continue
   it,walls=decode_wall(rom,stage,room);itrow.append(it)
   defs.extend((x,y,code,stage,room) for x,y,code in walls)
   objects=decode_room(rom,stage,room)
   for obj in objects['candles']:
    b=bytes.fromhex(obj['raw'])
    if b[4]==3 and b[9]&192==192:blocks.append((stage,room,int(obj['slot'],16),b[2],b[1],b[9]))
  row.append(len(defs));first.append(row);items.append(itrow)
 for stage in range(12,19):
  for room in range(counts[stage]):
   assert sum((s,r)==(stage,room) for x,y,c,s,r in defs)+sum((s,r)==(stage,room) for s,r,a,x,y,c in blocks)<=1,'late wall VRAM budget'
   assert items[stage][room][1]==0,'late slot1 unexpectedly used'
 return rom,counts,defs,first,items,blocks

def generate():
 rom,counts,defs,first,items,blocks=collect()
 header=f'''/* Generated by tools/build_trade_data.py through5A49/5B1B. */
#ifndef VK_TRADE_DATA_H
#define VK_TRADE_DATA_H
#include "candles_md.h"
#define VK_TRADE_STAGES 19
#define VK_TRADE_ROOMS 12
#define VK_SHOP_PRICE_COUNT 9
#define VK_WALL_OBJECT_COUNT 16
#define VK_TRADE_WALL_DEF_COUNT {len(defs)}
extern const VKByte vk_wall_objects[VK_WALL_OBJECT_COUNT];
extern const VKByte vk_shop_prices[VK_SHOP_PRICE_COUNT][4];
extern const VKWallDef vk_trade_wall_defs[VK_TRADE_WALL_DEF_COUNT];
extern const VKWord vk_trade_wall_first[19][13];
extern const VKByte vk_trade_wall_items[19][12][2];
#endif
'''
 data='/* Generated by tools/build_trade_data.py. Included once by wall.c. */\n'
 data+='const VKByte vk_wall_objects[VK_WALL_OBJECT_COUNT] = {'+','.join(str(v) for v in rom[0x1B0B:0x1B1B])+'};\n'
 data+='const VKByte vk_shop_prices[VK_SHOP_PRICE_COUNT][4] = {\n'+''.join(' {'+','.join(str(v) for v in rom[0x5428+4*i:0x542C+4*i])+'},\n' for i in range(9))+'};\n'
 data+='static const VKByte vk_trade_result[4][8]={\n'+''.join(' {'+','.join(str(v) for v in rom[0x5300+8*i:0x5308+8*i])+'},\n' for i in range(4))+'};\n'
 data+='static const VKByte vk_trade_frame[7]={'+','.join(str(v) for v in rom[0x5320:0x5327])+'};\n'
 data+='const VKWallDef vk_trade_wall_defs[VK_TRADE_WALL_DEF_COUNT]={\n'+''.join(f' {{{x},{y},{code}}}, /* stage{s} room{r} */\n' for x,y,code,s,r in defs)+'};\n'
 data+='const VKWord vk_trade_wall_first[19][13]={\n'+''.join(' {'+','.join(map(str,row))+'},\n' for row in first)+'};\n'
 data+='const VKByte vk_trade_wall_items[19][12][2]={\n'+''.join(' {'+','.join('{'+','.join(map(str,it))+'}' for it in row)+'},\n' for row in items)+'};\n'
 return {'trade_data.h':header,'trade_data.inc':data},(counts,defs,items,blocks)

def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out,meta=generate()
 for name,s in out.items():
  dest=ROOT/'sgdk/src/generated'/name
  if a.check:assert dest.read_text()==s,name
  else:dest.write_text(s)
 print('Trade data:19 stages,16 wall selectors,9 ROM products,',len(meta[1]),'direct walls,',len(meta[3]),'hidden blocks', 'CHECK PASS' if a.check else 'generated')
if __name__=='__main__':main()
