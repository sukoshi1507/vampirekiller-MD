#!/usr/bin/env python3
"""Generate the candles, fixed objects and object tiles of stages 0-2 for SGDK.

Usage: scratchpad/venv/bin/python tools/build_candles_md.py ROM [SNAPSHOT_BASE]
Writes sgdk/src/generated/candles_md.c and .h (never hand edit).

Room data: castle_room_objects.decode_room runs the ROM routines 5A49 and 5B1B
(research/castle-candles.md). Candle slots C470-C4F0 give X, Y, mode (+4) and the
dropped object (+5); type 83 records of C500-C5F0 are the fixed objects (gold key
0x17, chest 0x19 with its content in byte +13).

Tiles: objects are not sprites on the MSX, they are copied with transparency into
the SCREEN 5 bitmap from VRAM page 1 (object k at x 16*((k-1) mod 16),
y 336 + 16*((k-1) div 16); 0x21 and 0x22 are the two wall candle frames). The
HUD digits 0-9 sit at y 320, x 0..79 of the same page; they are the codes
0x20..0x29 of the text font of 4AE7/4B41 (code c at x 8*(c & 1F),
y 256 + 38h + (c & E0) / 4; text codes are ASCII - 0x10), exported as
vk_msx_font_tiles for the codes 0x20..0x5F. The page is read from an
openMSX VRAM snapshot (default scratchpad/type5/out/A/snaps/f02958_r2_8084888C,
hall room 2, not versioned); the same sheet is loaded in the courtyard, the hall
and stage 2. Pixels are MSX palette indices, i.e. PAL0 indices on the MD.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))

import castle_room_objects  # noqa: E402
from probe import load_rom  # noqa: E402

OUT = ROOT / 'sgdk/src/generated'
DEFAULT_SNAPSHOT = ROOT / 'scratchpad/type5/out/A/snaps/f02958_r2_8084888C'
STAGES = {0: 3, 1: 8, 2: 6}       # rooms per stage (courtyard, hall, stage 2)
MAX_ROOMS = 8
OBJECT_COUNT = 0x22               # sheet entries 1..0x22
PAGE1 = 256
DIGIT_Y = PAGE1 + 64
SHEET_Y = PAGE1 + 80
FONT_FIRST, FONT_COUNT = 0x20, 0x40


def pixel_reader(base):
    vram = Path(str(base) + '.vram').read_bytes()

    def pixel(x, y):
        byte = vram[y * 128 + x // 2]
        return byte >> 4 if x % 2 == 0 else byte & 15
    return pixel


def tile(pixel, x0, y0):
    words = []
    for row in range(8):
        word = 0
        for x in range(8):
            word = (word << 4) | pixel(x0 + x, y0 + row)
        words.append(word)
    return words


def sprite_tiles(pixel, x0, y0):
    """16x16 block in SGDK sprite order: column-major (TL, BL, TR, BR)."""
    out = []
    for cx in (0, 8):
        for cy in (0, 8):
            out.extend(tile(pixel, x0 + cx, y0 + cy))
    return out


def words(values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append('    ' + ', '.join(f'0x{v:08X}UL' for v in values[i:i + 8]) + ',')
    return lines


def main():
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 1
    data = load_rom(Path(sys.argv[1]))
    snapshot = Path(sys.argv[2]) if len(sys.argv) == 3 else DEFAULT_SNAPSHOT
    pixel = pixel_reader(snapshot)

    candles, objects = [], []
    candle_first = {s: [] for s in STAGES}
    object_first = {s: [] for s in STAGES}
    for stage, count in STAGES.items():
        for room in range(MAX_ROOMS + 1):
            candle_first[stage].append(len(candles))
            object_first[stage].append(len(objects))
            if room >= count:
                continue
            decoded = castle_room_objects.decode_room(data, stage, room)
            for c in decoded['candles']:
                raw = bytes.fromhex(c['raw'])
                candles.append((raw[2], raw[1], raw[4], raw[5], stage, room))
            for o in decoded['other_objects']:
                raw = bytes.fromhex(o['raw'])
                if raw[0] == 0x83:
                    objects.append((raw[2], raw[1], raw[4], raw[13], stage, room))

    sheet = []
    for k in range(1, OBJECT_COUNT + 1):
        sheet.extend(sprite_tiles(pixel, 16 * ((k - 1) % 16), SHEET_Y + 16 * ((k - 1) // 16)))
    digits = []
    for d in range(10):
        digits.extend(tile(pixel, 8 * d, DIGIT_Y))
    font = []
    for c in range(FONT_FIRST, FONT_FIRST + FONT_COUNT):
        font.extend(tile(pixel, 8 * (c & 0x1F), PAGE1 + 0x38 + ((c & 0xE0) >> 2)))
    assert font[:len(digits)] == digits

    src = [
        '/* Generated by tools/build_candles_md.py. Never hand edit. */',
        '#include "candles_md.h"',
        '',
        '/* x, y, mode (+4: 0 candle, 1 courtyard torch, 3 hidden block), object (+5). */',
        f'const VKCandleDef vk_candle_defs[{len(candles)}] = {{',
    ]
    for x, y, mode, kind, stage, room in candles:
        src.append(f'    {{ {x}, {y}, {mode}, 0x{kind:02X} }},   /* stage {stage} room {room} */')
    src += ['};', '/* First candle of each room; room r has first[r + 1] - first[r]. */',
            f'const VKByte vk_candle_first[3][{MAX_ROOMS + 1}] = {{']
    for stage in STAGES:
        src.append('    { ' + ', '.join(str(v) for v in candle_first[stage]) + ' },')
    src += ['};', '', '/* x, y, object, content (+13, chest only). */',
            f'const VKCandleDef vk_fixed_object_defs[{len(objects)}] = {{']
    for x, y, kind, content, stage, room in objects:
        src.append(f'    {{ {x}, {y}, 0x{kind:02X}, 0x{content:02X} }},   /* stage {stage} room {room} */')
    src += ['};', f'const VKByte vk_fixed_object_first[3][{MAX_ROOMS + 1}] = {{']
    for stage in STAGES:
        src.append('    { ' + ', '.join(str(v) for v in object_first[stage]) + ' },')
    src += ['};', '', f'/* Objects 1..0x{OBJECT_COUNT:02X}, 4 sprite tiles each (PAL0 indices). */',
            f'const u32 vk_object_tiles[{len(sheet)}] = {{'] + words(sheet) + ['};', '',
            '/* HUD digits 0-9 (PAL0 indices). */',
            f'const u32 vk_hud_digit_tiles[{len(digits)}] = {{'] + words(digits) + ['};', '',
            f'/* Text font codes 0x{FONT_FIRST:02X}..0x{FONT_FIRST + FONT_COUNT - 1:02X} (ASCII - 0x10): 0 background, 14 ink. */',
            f'const u32 vk_msx_font_tiles[{len(font)}] = {{'] + words(font) + ['};', '']

    header = [
        '/* Generated by tools/build_candles_md.py. Never hand edit. */',
        '#ifndef VK_CANDLES_MD_H',
        '#define VK_CANDLES_MD_H',
        '#include "../player.h"',
        'typedef struct { VKByte x, y, mode, kind; } VKCandleDef;',
        f'#define VK_OBJECT_SHEET_COUNT 0x{OBJECT_COUNT:02X}',
        f'#define VK_CANDLE_DEF_COUNT {len(candles)}',
        f'#define VK_FIXED_OBJECT_COUNT {len(objects)}',
        f'extern const VKCandleDef vk_candle_defs[{len(candles)}];',
        f'extern const VKByte vk_candle_first[3][{MAX_ROOMS + 1}];',
        f'extern const VKCandleDef vk_fixed_object_defs[{len(objects)}];',
        f'extern const VKByte vk_fixed_object_first[3][{MAX_ROOMS + 1}];',
        '#endif',
        '',
    ]
    tiles_header = [
        '/* Generated by tools/build_candles_md.py. Never hand edit. */',
        '#ifndef VK_OBJECT_TILES_MD_H',
        '#define VK_OBJECT_TILES_MD_H',
        '#include <genesis.h>',
        f'extern const u32 vk_object_tiles[{len(sheet)}];',
        f'extern const u32 vk_hud_digit_tiles[{len(digits)}];',
        f'#define VK_MSX_FONT_FIRST 0x{FONT_FIRST:02X}',
        f'#define VK_MSX_FONT_COUNT {FONT_COUNT}',
        f'extern const u32 vk_msx_font_tiles[{len(font)}];',
        '#endif',
        '',
    ]
    # Room data (native tests) and tiles (SGDK only) live in separate files.
    split = src.index('/* Objects 1..0x{:02X}, 4 sprite tiles each (PAL0 indices). */'.format(OBJECT_COUNT))
    (OUT / 'candles_md.c').write_text('\n'.join(src[:split]) + '\n')
    (OUT / 'object_tiles_md.c').write_text('\n'.join(
        ['/* Generated by tools/build_candles_md.py. Never hand edit. */',
         '#include "object_tiles_md.h"', ''] + src[split:]))
    (OUT / 'candles_md.h').write_text('\n'.join(header))
    (OUT / 'object_tiles_md.h').write_text('\n'.join(tiles_header))
    print(f'{len(candles)} candles, {len(objects)} fixed objects, {OBJECT_COUNT} object tiles')
    return 0


if __name__ == '__main__':
    sys.exit(main())
